/*  V86_KBD.H — ゲスト用の仮想 8251A (キーボード)                           */
/*                                                                          */
/*  キーボードは PIC と同じで「ゲスト専用デバイス」ではない。OS32 自身が     */
/*  IRQ1 でスキャンコードを受けてシェルを動かしている。しかも 8251A の       */
/*  データレジスタ (0x41) は**読んだら消える**ので、素通しにすると先に       */
/*  読んだ側がスキャンコードを奪い、もう一方には二度と届かない。            */
/*                                                                          */
/*  だから経路はこうする:                                                   */
/*                                                                          */
/*    実 IRQ1 → OS32 の kbd_irq_handler が 0x41 を読む                      */
/*             → セッション中なら v86_kbd_push() で FIFO へ入れ、           */
/*               OS32 自身のリングバッファには入れない                       */
/*             → irq_stub_1 が V86_REFLECT 1 でゲストの ISR を起動          */
/*             → ゲストが 0x41 を読むと #GP → v86_kbd_in() が FIFO から返す */
/*                                                                          */
/*  ゲストから見ると実機と同じ「IRQ1 が来て 0x41 を読むと 1 バイト取れる」。 */
/*  OS32 から見ると実チップは 1 回しか読まれない。                          */
/* ======================================================================== */

#ifndef __V86_KBD_H
#define __V86_KBD_H

#include "types.h"

/* PC-98 のキーボードポート。0x41 がデータ、0x43 がコマンド/ステータス。 */
#define V86_KBD_DATA    0x0041
#define V86_KBD_CMD     0x0043

/* セッション開始時に FIFO と修飾キー状態を捨てる */
void v86_kbd_reset(void);

/* このポートを仮想キーボードが持つか */
int  v86_kbd_is_port(u16 port);

u32  v86_kbd_in(u16 port);
void v86_kbd_out(u16 port, u32 value);

/* OS32 の IRQ1 ハンドラから。生のスキャンコード (メイクもブレイクも) を積む。
 * 戻り値が 0 でないときは脱出ホットキー (CTRL+STOP、または
 * 旧来の CTRL+GRPH+DEL) が押されたのでセッションを畳む。 */
int  v86_kbd_push(u8 scancode);

/* FIFO にゲストがまだ読んでいないバイトがあるか (IRQ1 反射の判断用) */
int  v86_kbd_pending(void);

/* 診断用カウンタ。ホストから 3 本まとめて読めるように並べてある。
 *   emu_read_mem addr=v86_kbd_n_push len=12 */
extern u32 v86_kbd_n_push;      /* ISR が FIFO に積んだ数 */
extern u32 v86_kbd_n_read;      /* ゲストが 0x41 から読んだ数 */
extern u32 v86_kbd_n_drop;      /* FIFO 満杯で捨てた数 */

#endif /* __V86_KBD_H */
