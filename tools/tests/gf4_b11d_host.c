static bool pal_lines(u32 norm)
{
    return norm==PAL || norm==PAL_N || norm==PAL_NC || norm==HD576I;
}
static bool ctv_norm(u32 norm)
{
    return norm==HD480P || norm==HD576P || norm==HD720P || norm==HD1080I;
}
static void timing_equal(const struct gf4_timing *a,const struct gf4_timing *b)
{
    assert(a->khz==b->khz && a->hd==b->hd && a->hs==b->hs && a->he==b->he &&
        a->ht==b->ht && a->vd==b->vd && a->vs==b->vs && a->ve==b->ve &&
        a->vt==b->vt && a->flags==b->flags);
}
static void check_ld(u32 norm)
{
    struct gf4_edid_state modes;
    gf2_host_memset(&modes,0xa5,sizeof(modes));
    assert(gf4_tv_modes(norm,&modes)==GF4_OK);
    assert(modes.version==GF4_EDID_VERSION && modes.size==sizeof(modes) &&
        modes.base_valid && !modes.digital && !modes.truncated && !modes.last_rc &&
        modes.preferred==0 && modes.ntiming==sizeof(ld)/sizeof(ld[0]) &&
        modes.extensions==0 && modes.next_block==0 && !modes.range_valid);
    u32 height=pal_lines(norm) ? 576 : 480;
    assert(modes.timing[0].hd==720 && modes.timing[0].vd==height);
    bool seen[sizeof(ld)/sizeof(ld[0])]={false};
    for (u32 index=0;index<modes.ntiming;++index) {
        const struct gf4_timing *t=&modes.timing[index];
        u32 which=0;
        while (which<sizeof(ld)/sizeof(ld[0]) &&
            (ld[which].hd!=t->hd || ld[which].vd!=
                ((t->flags&GF4_DBLSCAN) ? t->vd/2U : t->vd))) ++which;
        assert(which<sizeof(ld)/sizeof(ld[0]) && !seen[which]); seen[which]=true;
        struct gf4_timing expected=ld[which];
        /* Independent staged integer rounding, T:215-220. */
        u32 line_khz=(pal_lines(norm) ? 50000U : 59940U)*expected.ht/1000U;
        expected.khz=line_khz*expected.vt/1000U;
        if (expected.flags&GF4_DBLSCAN) {
            expected.khz*=2; expected.vd*=2; expected.vs*=2;
            expected.ve*=2; expected.vt*=2;
        }
        timing_equal(t,&expected);
        struct gf4_tv_state image;
        gf2_host_memset(&image,0xa5,sizeof(image));
        assert(gf4_tv_state_calc(norm,t,&image)==GF4_OK);
        assert(image.version==GF4_TV_VERSION && image.size==sizeof(image) && image.norm==norm);
        assert(!gf2_host_memcmp(image.enc,enc_expected[norm],sizeof(image.enc)));
        assert(!gf2_host_memcmp(image.ptv,height==576 ? ptv_576 : ptv_480,sizeof(image.ptv)));
        assert(!gf2_host_memcmp(image.hfilter,filter_expected[height==576][which][0],sizeof(image.hfilter)));
        assert(!gf2_host_memcmp(image.vfilter,filter_expected[height==576][which][1],sizeof(image.vfilter)));
        for (u32 row=0;row<4;++row) for (u32 tap=0;tap<7;++tap)
            assert(image.hfilter2[row][tap]==0);
        for (u32 i=0;i<sizeof(image.ctv)/sizeof(image.ctv[0]);++i) assert(image.ctv[i]==0);
    }
}
static void check_hd(const struct hd_row *r)
{
    struct gf4_edid_state modes;
    assert(gf4_tv_modes(r->norm,&modes)==GF4_OK);
    assert(modes.base_valid && modes.preferred==0 && modes.ntiming==r->count);
    timing_equal(&modes.timing[0],&r->preferred);
    for (u32 i=0;i<modes.ntiming;++i) {
        struct gf4_tv_state image;
        const struct gf4_timing *t=&modes.timing[i];
        assert(t->hd<=r->preferred.hd && t->vd<=r->preferred.vd);
        assert(!(t->flags&GF4_DBLSCAN));
        assert((t->flags&GF4_INTERLACE)==(r->preferred.flags&GF4_INTERLACE));
        gf2_host_memset(&image,0xa5,sizeof(image));
        assert(gf4_tv_state_calc(r->norm,t,&image)==GF4_OK);
        assert(image.version==GF4_TV_VERSION && image.size==sizeof(image) && image.norm==r->norm);
        assert(!gf2_host_memcmp(image.ctv,ctv_expected[r->norm],sizeof(image.ctv)));
        for (u32 j=0;j<sizeof(image.enc);++j) assert(image.enc[j]==0);
        for (u32 j=0;j<sizeof(image.ptv)/sizeof(image.ptv[0]);++j) assert(image.ptv[j]==0);
        for (u32 row=0;row<4;++row) for (u32 tap=0;tap<7;++tap)
            assert(!image.hfilter[row][tap] && !image.hfilter2[row][tap] && !image.vfilter[row][tap]);
    }
}
/* Independently worked CVT modelines: Xorg MIT xf86cvt.c:92-95,
 * 155-209,249-262, URL in tv_data.c. The interlaced CVT uses a 120Hz
 * field rate before T:277-290 overrides H/V timings for 1080i. */
static void check_cvt_inputs(void)
{
    static const struct gf4_timing vga={23750,640,664,720,800,480,483,487,500,GF4_NEG_H};
    /* 720x576 at 60Hz, xf86cvt.c:155-209,249-251: period=27.835us,
     * HBlank=192, VSyncAndBackPorch=20; 5:4 VSync=7 (:137-138).
     * Clock=floor((912*1000/27.835348)/250)*250=32750 kHz.
     * At :202-205 integer sync width
     * is floor(912*8/100)=72; start=816-72=744, then next cell=752.
     * This distinguishes division before subtraction from after it. */
    static const struct gf4_timing pal_cvt_60hz={32750,720,752,816,912,
        576,579,586,599,GF4_NEG_H};
    static const struct gf4_timing xga_i={66750,1024,2080,2088,2200,384,542,544,562,
        GF4_NEG_H|GF4_INTERLACE};
    struct gf4_edid_state modes;
    assert(!gf4_tv_modes(HD720P,&modes));
    bool found=false,found_pal=false;
    for (u32 i=0;i<modes.ntiming;++i) {
        if (modes.timing[i].hd==640 && modes.timing[i].vd==480) {
            timing_equal(&modes.timing[i],&vga); found=true;
        }
        if (modes.timing[i].hd==pal_cvt_60hz.hd && modes.timing[i].vd==pal_cvt_60hz.vd) {
            timing_equal(&modes.timing[i],&pal_cvt_60hz); found_pal=true;
        }
    }
    assert(found && found_pal);
    assert(!gf4_tv_modes(HD1080I,&modes)); found=false;
    for (u32 i=0;i<modes.ntiming;++i)
        if (modes.timing[i].hd==1024 && modes.timing[i].vd==384) {
            timing_equal(&modes.timing[i],&xga_i); found=true;
        }
    assert(found);
}
static void fails_unchanged(u32 norm,const struct gf4_timing *t,i32 rc)
{
    struct gf4_tv_state image,before;
    gf2_host_memset(&image,0xa5,sizeof(image));
    gf2_host_memcpy(&before,&image,sizeof(image));
    assert(gf4_tv_state_calc(norm,t,&image)==rc);
    assert(!gf2_host_memcmp(&before,&image,sizeof(image)));
}
static void invalid_inputs(void)
{
    struct gf4_edid_state modes,before;
    gf2_host_memset(&modes,0xa5,sizeof(modes));
    gf2_host_memcpy(&before,&modes,sizeof(modes));
    assert(gf4_tv_modes(NORMS,&modes)==GF4_EINVAL);
    assert(!gf2_host_memcmp(&before,&modes,sizeof(modes)));
    assert(gf4_tv_modes(U32_MAX,&modes)==GF4_EINVAL);
    assert(!gf2_host_memcmp(&before,&modes,sizeof(modes)));
    assert(gf4_tv_modes(PAL,NULL)==GF4_EINVAL);
    assert(gf4_tv_modes(NTSC_M,&modes)==GF4_OK);
    struct gf4_timing good=modes.timing[0],bad=good;
    struct gf4_tv_state out;
    assert(gf4_tv_state_calc(NTSC_M,&good,&out)==GF4_OK);
    fails_unchanged(NORMS,&good,GF4_EINVAL);
    fails_unchanged(U32_MAX,&good,GF4_EINVAL);
    fails_unchanged(NTSC_M,NULL,GF4_EINVAL);
    assert(gf4_tv_state_calc(NTSC_M,&good,NULL)==GF4_EINVAL);
    bad.khz=0; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    /* T:332-349: LD clock <=70MHz, rounded refresh tolerance 600mHz,
     * no interlace. Normal control above must continue to succeed. */
    bad=good; bad.khz=70001; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.khz/=2; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.flags|=GF4_INTERLACE; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.flags|=0x10U; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.hd=0; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.hs=bad.hd; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    bad=good; bad.ve=bad.vs; fails_unchanged(NTSC_M,&bad,GF4_ERANGE);
    /* T:317-329: CTV clock/size/scan constraints. */
    good=hd[2].preferred;
    assert(gf4_tv_state_calc(HD720P,&good,&out)==GF4_OK);
    bad=good; bad.khz=400001; fails_unchanged(HD720P,&bad,GF4_ERANGE);
    bad=good; bad.hd=1281; fails_unchanged(HD720P,&bad,GF4_ERANGE);
    bad=good; bad.vd=721; fails_unchanged(HD720P,&bad,GF4_ERANGE);
    bad=good; bad.flags|=GF4_DBLSCAN; fails_unchanged(HD720P,&bad,GF4_ERANGE);
    bad=good; bad.flags|=GF4_INTERLACE; fails_unchanged(HD720P,&bad,GF4_ERANGE);
    bad=hd[3].preferred; bad.flags=0; fails_unchanged(HD1080I,&bad,GF4_ERANGE);
}
void _start(void)
{
    for (u32 norm=0;norm<NORMS;++norm) if (!ctv_norm(norm)) check_ld(norm);
    for (u32 i=0;i<sizeof(hd)/sizeof(hd[0]);++i) check_hd(&hd[i]);
    check_cvt_inputs();
    invalid_inputs();
    gf2_host_exit(0);
}
