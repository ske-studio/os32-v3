#!/usr/bin/env python3
"""Bind the immutable HWDEV manifest to the built kernel/KDEBUG pair."""
import argparse
from pathlib import Path
import struct
import zlib
from mkmod import pair_crc
from module_schema import HEADER_FIELDS


def generate(kernel, core, out):
    pair = pair_crc(kernel.read_bytes())
    data = bytearray(core.read_bytes())
    header = dict(zip(HEADER_FIELDS, struct.unpack_from('<36I', data)))
    crc = header['IMAGE_CRC']
    struct.pack_into('<I', data, HEADER_FIELDS.index('IMAGE_CRC') * 4, 0)
    if header['ID'] != 1 or header['PAIR_CRC'] != pair or zlib.crc32(data) != crc:
        raise ValueError('invalid KDEBUG/kernel pair')
    write_header(pair, crc, out)


def write_header(pair, crc, out):
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('/* Generated by gen_hwdev_pair.py; do not edit. */\n'
                   f'#define HWDEV_KERNEL_PAIR_CRC 0x{pair:08x}U\n'
                   f'#define HWDEV_CORE_IMAGE_CRC 0x{crc:08x}U\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--kernel', type=Path, required=True)
    p.add_argument('--core', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    a = p.parse_args()
    generate(a.kernel, a.core, a.out)
