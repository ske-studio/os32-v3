#!/usr/bin/env python3
"""Generate the S1p PC-98 keysym table from FreeBSD jp.pc98.kbd."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SHA256 = '354468f80d0ec869f28d867bcb819e0c04c78eb1e001232303c81e9684007433'
VOID = 0xf500
CONTROL = dict(zip(('nul soh stx etx eot enq ack bel bs ht nl vt ff cr so si '
                    'dle dc1 dc2 dc3 dc4 nak syn etb can em sub esc fs gs rs us').split(), range(32)))
CONTROL['del'] = 127
# Values from NetBSD wsksymdef.h and FreeBSD kbio.h.
SPECIAL = {'nop': (VOID, 1, 0), 'lshift': (0xf101, 0, 0),
           'clock': (0xf105, 0, 0), 'lalt': (0xf107, 0, 0),
           'lctrl': (0xf103, 0, 0), 'btab': (VOID, 1, 8),
           'meta': (VOID, 1, 0x84), 'slock': (0xf10c, 0, 0),
           'boot': (VOID, 1, 0x85), 'debug': (VOID, 1, 0x86),
           'susp': (VOID, 1, 0x87), 'saver': (VOID, 1, 0x88),
           'nscr': (VOID, 1, 0x0a)}
# B §2a, applied before generating exact and group cells.
DOS = {0: 0x1b, 15: 9, 28: 13, 53: 0xf115, 54: 0x12,
       55: 3, 56: 0x16, 57: 0x7f, 58: 0x1e, 59: 0x1d,
       60: 0x1c, 61: 0x1f, 62: 1, 63: 5, 81: 0xf116,
       82: 0, 83: 0, 84: 0, 97: 0,
       **{i: 0 for i in range(98, 108)}}
TOKEN = re.compile(r"'(?:[^'])'|'''|\S+")


def cell(token):
    if len(token) == 3 and token[0] == token[-1] == "'":
        return (ord(token[1]), 0, 0)
    if token in CONTROL:
        return (CONTROL[token], 0, 0)
    if token in SPECIAL:
        return SPECIAL[token]
    match = re.fullmatch(r'(fkey|scr)(\d+)', token)
    if match:
        n = int(match[2])
        if match[1] == 'fkey' and 1 <= n <= 96:
            return (VOID, 1, 0x1a + n)
        if match[1] == 'scr' and 1 <= n <= 16:
            return (VOID, 1, 0x0a + n)
    raise ValueError('unsupported token: ' + token)


def parse(data):
    rows = []
    for line in data.splitlines():
        if not re.match(r'^\s*\d{3}\s', line):
            continue
        fields = TOKEN.findall(line)
        if len(fields) != 10 or int(fields[0]) != len(rows) or fields[-1] not in 'OCNB':
            raise ValueError('invalid key row: ' + line)
        rows.append(([cell(t) for t in fields[1:9]], 'OCNB'.index(fields[-1])))
    if len(rows) != 128:
        raise ValueError('expected 128 rows and no additional bank')
    for key, value in DOS.items():
        rows[key] = ([(value, 0, 0)] * 8, rows[key][1])
    for key in (96, 114):
        rows[key] = ([SPECIAL['nop']] * 8, rows[key][1])
    return rows


def render(rows):
    out = ['/* Generated by tools/kbd_import.py; S1p staging, not linked. */',
           '/* FreeBSD、BSD-2-Clause (kbdtables.h) */',
           '/* FreeBSD releng/10.4 d869f4ade283f4691dc249e435376a5883824be2 */',
           '/* jp.pc98.kbd SHA256 ' + SHA256 + ' */',
           '#include "input/hal/keymap.h"', '',
           'static const KmEntry s1p_entries[128] = {']
    for cells, _ in rows:
        a, b = cells[0][0], cells[1][0]
        out.append('    {0x%04x, {0x%04x, 0x%04x}, {0x%04x, 0x%04x}},' % (VOID, a, b, a, b))
    out += ['};', 'static const KmExactCell s1p_bank0[128][8] = {']
    for index, (cells, _) in enumerate(rows):
        out.append('    {' + ', '.join('{0x%04x, %d, %d}' % c for c in cells) + '}, /* %03d */' % index)
    out += ['};', 'static const u8 s1p_flags[128] = {']
    for pos in range(0, 128, 16):
        out.append('    ' + ', '.join(str(r[1]) for r in rows[pos:pos+16]) + ',')
    out += ['};', 'static const u8 s1p_compat[128] = {']
    for pos in range(0, 128, 16):
        out.append('    ' + ', '.join('0x%02x' % i for i in range(pos, pos+16)) + ',')
    out += ['};', 'static const KmPc98Extensions s1p_ext = { s1p_bank0, 0, s1p_flags, 0, 0 };',
            'const KmBackend s1p_pc98_backend = { KM_MAP_PC98, 128, s1p_entries, s1p_compat, 0, &s1p_ext };', '']
    return '\n'.join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('source', type=Path)
    p.add_argument('output', type=Path)
    p.add_argument('--product', action='store_true', help='export pc98_jp_backend for S1pt')
    args = p.parse_args()
    data = args.source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        p.error('source SHA256 mismatch')
    text = render(parse(data.decode('ascii')))
    if args.product:
        text = text.replace('s1p_pc98_backend', 'pc98_jp_backend')
    args.output.write_text(text)


if __name__ == '__main__':
    main()
