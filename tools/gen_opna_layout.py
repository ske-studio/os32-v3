"""Emit the C ABI layout from Rust host and OS32 object files, without running guest code."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'lib/os32_opna'
HEADER = CORE / 'opna_layout.h'
TARGET = ROOT / 'sdk/rust/i386-os32-snd.json'


def layout(work, flags):
    obj = work / 'layout.o'
    raw = work / 'layout.bin'
    subprocess.run(['rustc', '--edition=2021', '--crate-type=lib', '-Cpanic=abort',
                    *flags, '--emit=obj', work / 'layout.rs', '-o', obj], check=True)
    subprocess.run(['objcopy', '--dump-section', f'.opna_layout={raw}', obj], check=True)
    return struct.unpack('<6I', raw.read_bytes())


def generate(deps):
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / 'layout.rs').write_text(f'''#![no_std]
#[path="{CORE}/src/state.rs"] mod state;
use core::mem::{{align_of, size_of, offset_of}};
use state::{{OpnaState, TimerState}};
#[used] #[link_section=".opna_layout"]
static LAYOUT: [u32; 6] = [size_of::<usize>() as u32, size_of::<OpnaState>() as u32,
    align_of::<OpnaState>() as u32, offset_of!(OpnaState, timer) as u32,
    size_of::<TimerState>() as u32, align_of::<TimerState>() as u32];
''')
        flags = ['-Zunstable-options', '--target', TARGET, '-L', f'dependency={deps}']
        for name in ('core', 'compiler_builtins'):
            lib, = deps.glob(f'lib{name}-*.rlib')
            flags.extend(['--extern', f'{name}={lib}'])
        rows = sorted(set([layout(work, flags), layout(work, [])]))
    lines = ['/* Generated by tools/gen_opna_layout.py. */', '#ifndef OS32_OPNA_LAYOUT_H',
             '#define OS32_OPNA_LAYOUT_H']
    for i, (width, *values) in enumerate(rows):
        lines.append(f'#{"elif" if i else "if"} __SIZEOF_POINTER__ == {width}')
        for name, value in zip(('STATE_BYTES', 'STATE_ALIGN', 'TIMER_OFFSET',
                                'TIMER_BYTES', 'TIMER_ALIGN'), values):
            lines.append(f'#define OPNA_{name} {value}u')
    return '\n'.join([*lines, '#else', '#error Unsupported OPNA pointer width',
                      '#endif', '#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('deps', type=Path, help='release/deps from make opna-staticlib')
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    header = generate(args.deps.resolve())
    if args.write:
        HEADER.write_text(header)
    elif HEADER.read_text() != header:
        raise SystemExit('stale OPNA layout; regenerate with --write')
