#!/usr/bin/env python3
"""Generate SQLite typed imports, facade/stubs and the owner-pool VFS body.

The same input drives both sides of the paired module contract.
"""
import argparse
import json
from pathlib import Path
import re

from gen_kdebug_imports import declaration, abi_hash, fnv1a

ROOT = Path(__file__).resolve().parents[1]
DEFINITION = ROOT / 'tools/prototypes/sqlite_imports.def'


def generate(out, definition=DEFINITION, contracts_only=False, module="sqlite"):
    prefix = module.upper()
    doc = json.loads(Path(definition).read_text())
    if doc['schema'] != 1:
        raise ValueError('unknown paired import schema')
    entries = []
    names, hashes = set(), set()
    for index, row in enumerate(doc['imports']):
        name = row['symbol']
        if not re.fullmatch(r'[A-Za-z_]\w{0,62}', name) or name in names:
            raise ValueError('invalid/duplicate paired import')
        hashed = fnv1a(name.encode())
        if hashed in hashes:
            raise ValueError('paired import hash collision')
        if row['context'] not in ('normal', 'normal,exception') or type(row['irq']) is not bool:
            raise ValueError('paired imports require a supported context and an IRQ permission')
        signature = row.get('declaration') or declaration(dict(row, kind='FUNC'), ROOT)
        if not re.search(r'\b' + name + r'\s*\([^;{}]*\);$', signature):
            raise ValueError('function import required')
        entries.append(dict(row, index=index, name=name, signature=signature,
                            kind=1, type_ver=1))
        names.add(name)
        hashes.add(hashed)
    facade = json.dumps(doc.get('facade', []), sort_keys=True)
    if module != 'sqlite':
        # Paired facade includes callback and public record layout contracts.
        facade += ''.join((ROOT / p).read_text() for p in doc['contracts'])
    module_abi = fnv1a((str(abi_hash(entries)) + facade).encode())
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    includes = sorted({e['source'] for e in entries if 'source' in e})
    header = ['/* Generated by gen_sqlite_imports.py; do not edit. */',
              f'#ifndef {prefix}_IMPORTS_GENERATED_H', f'#define {prefix}_IMPORTS_GENERATED_H',
              '#include "types.h"']
    header += [f'#include "{p}"' for p in includes]
    header += [e['signature'] for e in entries]
    header += [f'#define {prefix}_IMPORT_COUNT {len(entries)}',
               f'#define {prefix}_MODULE_ABI_GEN 0x{module_abi:08x}u',
               f'extern unsigned long {module}_import_slots[{prefix}_IMPORT_COUNT];', '#endif']
    (out / f'{module}_imports.h').write_text('\n'.join(header) + '\n')
    if not contracts_only:
        (out / f'{module}_import_slots.c').write_text(
            f'#include "{module}_imports.h"\nunsigned long {module}_import_slots[{prefix}_IMPORT_COUNT]\n'
            f'__attribute__((section(".data.{module}_import_slots"), aligned(4))) = {{0}};\n')
        asm = ['/* Generated i386 cdecl tail jumps, including variadic kprintf. */',
               f'.section .text.{module}_imports,"ax",@progbits', '.code32']
        for e in entries:
            n = e['name']
            asm += [f'.globl {n}', f'.type {n}, @function', f'{n}:',
                    f'    jmp *{module}_import_slots+{4*e["index"]}', f'.size {n}, .-{n}']
        asm += ['.section .note.GNU-stack,"",@progbits']
        (out / f'{module}_import_stubs.S').write_text('\n'.join(asm) + '\n')
        # Compile-only provider type check; deliberately not a resident kernel input.
        core = [f'#include "{module}_imports.h"']
        if module == 'sqlite':
            core += ['extern volatile u32 tick_count;',
                     'u32 ktime_ticks(void) { return tick_count; }']
        for e in entries:
            signature = e['signature'].replace('__cdecl ', '')
            pointer = re.sub(r'\b' + e['name'] + r'(?=\s*\()',
                             '(*' + module + '_type_' + e['name'] + ')', signature, count=1)
            core.append(pointer[:-1] + ' = ' + e['name'] + ';')
        (out / f'{module}_provider_types.c').write_text('\n'.join(core) + '\n')
    if module == "sqlite":
        generate_facade(out, doc["facade"], entries)
    else:
        generate_component_exports(out, entries, module)
    if module == "sqlite" and not contracts_only:
        source = (ROOT / 'lib/sqlite3/os32_sqlite_vfs.c').read_text()
        source = source.replace('static char sqlite_mem_pool[SQLITE_MEMSYS5_SIZE];',
                                'char *sqlite_module_pool;\n#define sqlite_mem_pool sqlite_module_pool')
        source = source.replace('extern volatile u32 tick_count;', '')
        source = source.replace('tick_count', 'ktime_ticks()')
        (out / 'os32_sqlite_vfs.c').write_text('#include "sqlite_imports.h"\n' + source)
    metadata = dict(module_abi_gen=module_abi, imports=entries)
    if not contracts_only:
        (out / f'{module}_imports.json').write_text(json.dumps(metadata, indent=2) + '\n')
    return metadata


def generate_facade(out, rows, entries):
    """One typed API/stub list for module and resident outer calls."""
    h = ['/* Generated by gen_sqlite_imports.py; do not edit. */',
         '#ifndef SQLITE_FACADE_GENERATED_H', '#define SQLITE_FACADE_GENERATED_H',
         '#include "os32_sqlite_config.h"', '#include "os32_sqlite_outer.h"', '#include <stdarg.h>',
         '#define SQLITE_MODULE_OPS_VERSION 2u',
         '#define SQLITE_MODULE_POOL_SIZE SQLITE_MEMSYS5_SIZE',
         'typedef struct {']
    for r in rows:
        h.append(f'    {r["result"]} (*{r["name"]})({r["args"]});')
    h += ['} SqliteModuleApi;', f'#define SQLITE_MODULE_API_SLOTS {len(rows)}u',
          'extern const SqliteModuleApi sqlite_stub_api;',
          'extern const SqliteModuleApi *sqlite_module_api;',
          'int sqlite_module_ready(void);']
    stubs, wrappers, bind, adapters = [], [], [], []
    for r in rows:
        name, ret, args, target, wrapper = (r[x] for x in ('name','result','args','target','wrapper'))
        arglist = [] if args == 'void' else args.split(', ')
        names = [re.search(r'(\w+)$', arg)[1] for arg in arglist]
        callargs = ', '.join(names)
        decl = f'{ret} {wrapper}({args})'
        h.append(decl + ';')
        stub = 'return;' if ret == 'void' else f'return {r["stub"]};'
        stubs += [f'static {ret} stub_{name}({args}) {{ ' +
                  ' '.join(f'(void){a};' for a in names) + ' ' + stub + ' }']
        fields = '; '.join(arglist) if arglist else ''
        if fields: fields += '; '
        if ret != 'void': fields += ret + ' result;'
        else: fields += 'int unused;'
        wrappers += [f'typedef struct {{ {fields} }} Call_{name};',
                     f'static void call_{name}(void *arg) {{', f'    Call_{name} *f = arg;', '    (void)f;']
        invocation = f'sqlite_module_api->{name}(' + ', '.join('f->'+a for a in names) + ')'
        wrappers += [('    f->result = ' if ret != 'void' else '    ') + invocation + ';', '}', decl, '{']
        # Missing component uses its typed stub. A present but unavailable
        # engine retains the pre-module SQLITE_MISUSE result for status calls.
        refused = 'SQLITE_MISUSE' if r['stub'] == 'OS32_ERR_NOSYS' else r['stub']
        init = callargs + (', ' if names else '') + (refused if ret != 'void' else '0')
        wrappers += [f'    Call_{name} f = {{{init}}};',
                     f'    if (!sqlite_module_ready()) ' +
                     (f'return sqlite_module_api->{name}({callargs});' if ret != 'void' else f'{{ sqlite_module_api->{name}({callargs}); return; }}'),
                     f'    sqlite_engine_run(call_{name}, &f, {r["io"]});',
                     ('    return f.result;' if ret != 'void' else '    return;'), '}']
        # Allocation class follows the connection/group, never the current app.
        db = 'db' if 'db' in names else '(stmt ? sqlite3_db_handle(stmt) : 0)' if 'stmt' in names else '0'
        group = 'group' if 'group' in names else '0'
        adapters += [f'static {ret} module_{name}({args}) {{',
                     f'    os32_sqlite_allocation_context({db}, {group});',
                     ('    return ' if ret != 'void' else '    ') + f'{target}({callargs});', '}']
        bind.append(f'    .{name} = module_{name},')
    stubs += ['const SqliteModuleApi sqlite_stub_api = {'] + [f'    .{r["name"]} = stub_{r["name"]},' for r in rows] + ['};']
    h += ['#endif']
    (out / 'sqlite_facade.h').write_text('\n'.join(h)+'\n')
    (out / 'sqlite_outer_calls.inc').write_text('\n'.join(stubs+wrappers)+'\n')
    (out / 'sqlite_facade_bind.inc').write_text('\n'.join(adapters + ['static const SqliteModuleApi api = {'] + bind + ['};'])+'\n')
    core = ['#include "sqlite_imports.h"', '#include "module_image.h"',
            'extern volatile u32 tick_count;', 'u32 ktime_ticks(void) { return tick_count; }',
            'const u32 sqlite_kexports[] = {']
    core += [f'    (u32)(uptr){e["name"]},' for e in entries]
    core += ['};', 'const struct module_symbol_contract sqlite_import_contracts[] = {']
    core += [f'    {{0x{fnv1a(e["name"].encode()):08x}u, 1, 1}},' for e in entries]
    core += ['};', 'const struct module_symbol_contract sqlite_export_contracts[] = {',
             f'    {{0x{fnv1a(b"initialize"):08x}u, 1, 0}},', '};']
    (out / 'sqlite_kexports.c').write_text('\n'.join(core)+'\n')


def generate_component_exports(out, entries, module):
    """Paired components use typed facades and the same function-only slots."""
    core = [f'#include "{module}_imports.h"', '#include "module_image.h"',
            f'const u32 {module}_kexports[] = {{']
    core += [f'    (u32)(uptr){e["name"]},' for e in entries]
    core += ['};', f'const struct module_symbol_contract {module}_import_contracts[] = {{']
    core += [f'    {{0x{fnv1a(e["name"].encode()):08x}u, 1, 1}},' for e in entries]
    core += ['};', f'const struct module_symbol_contract {module}_export_contracts[] = {{',
             f'    {{0x{fnv1a(b"initialize"):08x}u, 1, 0}},', '};']
    (out / f'{module}_kexports.c').write_text('\n'.join(core) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out-dir', type=Path, required=True)
    parser.add_argument('--contracts-only', action='store_true')
    parser.add_argument('--module', choices=('sqlite', 'fep', 'cd', 'kcg', 'fm', 'pcm', 'v86', 'lan', 'cirrus'), default='sqlite')
    args = parser.parse_args()
    definition = ROOT / f'tools/prototypes/{args.module}_imports.def'
    generate(args.out_dir, definition, contracts_only=args.contracts_only, module=args.module)
