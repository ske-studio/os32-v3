#!/usr/bin/env python3
"""Generate GF storage tables from compiler-evaluated, frozen oracle records.

No C initializer parsing and no oracle rewriting. Without --input, the frozen
oracle translation unit is evaluated by test_recover_tables.extract_oracle().
Auxiliary arrays and expression functions stay in recover_gf.c; references
retain their names.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/tests'))
from test_recover_tables import extract_oracle  # noqa: E402

OUTPUT = ROOT / 'kdebug/generated/recover_gf_tables.inc'
NONE = 0xffffffff


def narrow(value, bits, sentinel=False):
    limit = (1 << bits) - 1
    if sentinel and value == NONE:
        return f'REC_TABLE_NONE{bits}'
    if not isinstance(value, int) or not 0 <= value <= limit - int(sentinel):
        raise ValueError(f'{value!r} does not fit {bits} bits (NONE={sentinel})')
    return f'0x{value:x}U'


def generate(data):
    if data['schema'] != 1:
        raise ValueError('unsupported extraction schema')
    tables = {}
    for table, row, field, slot, value in data['records']:
        if slot == 0:
            tables.setdefault(table, {}).setdefault(row, {})[field] = value
    def rows(name):
        table = tables[name]
        if sorted(table) != list(range(len(table))):
            raise ValueError(f'{name}: non-contiguous ordinals')
        return [table[i] for i in range(len(table))]
    def ref(value):
        if value == 'NULL':
            return '0'
        if not isinstance(value, str) or not value.isidentifier():
            raise ValueError(f'invalid reference {value!r}')
        return value
    def fields(row, specs):
        return [ref(row[f]) if bits == 0 else narrow(row[f], bits, sentinel)
                for f, bits, sentinel in specs]
    rules, targets, layouts = rows('rules'), rows('targets'), rows('layouts')
    for name, values in [('rule', rules), ('target', targets), ('layout', layouts)]:
        if len(values) != tables['profile'][0][name + '_count']:
            raise ValueError(f'{name}: count mismatch')
    rule_specs = [(f, 32, False) for f in
                  ['substep', 'write_mask', 'verify_mask', 'value.mask',
                   'value.bits', 'value.min', 'value.max']]
    rule_specs += [(f, 0, False) for f in ['value.allowed', 'requires', 'guards']]
    rule_specs += [('id', 16, False), ('key', 16, False), ('pc', 16, True),
                   ('value.allowed_count', 16, False), ('phase', 8, False),
                   ('main_id', 8, True), ('value.mode', 8, False),
                   ('value.expr_id', 8, True), ('flags', 8, False),
                   ('requires_count', 8, False), ('guard_count', 8, False)]
    target_specs = [('offset', 32, False), ('index', 32, False), ('port', 16, False)]
    target_specs += [(f, 8, False) for f in
                     ['space', 'bar', 'head', 'width', 'access', 'read_safe']]
    ranges = []
    for ordinal, row in enumerate(layouts):
        # Preserve reference identity as well as contents; only adjacent +1 rows.
        signature = tuple(row[f] for f in ['opcode', 'kinds', 'argc', 'dir_substep', 'flags'])
        if ranges and ranges[-1][3] == signature and row['substep'] == ranges[-1][1] + 1:
            ranges[-1][1] = row['substep']
        else:
            ranges.append([row['substep'], row['substep'], ordinal, signature])
    out = ['/* Generated by tools/gen_recover_tables.py; do not edit. */']
    for name, values in [('RULE', rules), ('TARGET', targets), ('LAYOUT', layouts), ('RANGE', ranges)]:
        out.append(f'#define REC_GF_{name}_COUNT {len(values)}U')
    def array(ctype, name, values):
        out.append(f'static const struct {ctype} {name}[] = {{')
        out.extend('    {' + ', '.join(row) + '},' for row in values)
        out.append('};')
    array('recover_rule_small', 'rules_small', [fields(r, rule_specs) + ['0'] for r in rules])
    array('recover_target_small', 'targets_small', [fields(r, target_specs) for r in targets])
    array('recover_layout_range', 'layout_ranges', [
        [narrow(first, 32), narrow(last, 32), ref(sig[1]), narrow(sig[0], 16),
         narrow(ordinal, 16), narrow(sig[2], 8), narrow(sig[3], 8, True),
         narrow(sig[4], 8), '0'] for first, last, ordinal, sig in ranges])
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=pathlib.Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(args.input.read_text()) if args.input else extract_oracle()
    result = generate(data)
    from gfinit_mode_tables import generate as generate_mode
    mode_output = ROOT / "kdebug/generated/recover_gf_c_tables.inc"
    mode_result = generate_mode(data)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('recover GF generated tables are stale')
        if not mode_output.exists() or mode_output.read_text() != mode_result:
            raise SystemExit('recover GF C generated tables are stale')
        print('PASS recover GF default/C generated tables reproducible')
    else:
        OUTPUT.write_text(result)
        mode_output.write_text(mode_result)


if __name__ == '__main__':
    main()
