#!/usr/bin/env python3
"""Generate the kernel's KMOD schema view from module_schema.py."""
import argparse
from pathlib import Path

from module_schema import (CONSTANTS, HEADER_FIELDS, POLICIES, POLICY_FIELDS,
                           COMPONENTS, MODULE_RECORD_CAP, validate_components)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'kernel/module_schema.h'


def render():
    validate_components()
    lines = ['/* Generated by tools/gen_module_schema.py; do not edit. */',
             '#ifndef MODULE_SCHEMA_H', '#define MODULE_SCHEMA_H', '']
    for name, value in CONSTANTS.items():
        lines.append(f'#define MODULE_{name} {value}U')
    max_slots = max(policy['ops_slots'] for policy in POLICIES.values())
    lines += [f'#define MODULE_RUNTIME_SLOTS {max_slots}U',
              f'#define MODULE_RECORD_CAP {MODULE_RECORD_CAP}U']
    required = ', '.join('"' + row['path'] + '"' for row in COMPONENTS if row['required'])
    lines += [f'#define MODULE_REQUIRED_PATHS {{ {required} }}']
    lines += ['', '/* Compatibility names for the existing KDEBUG contracts. */']
    kdebug = POLICIES[CONSTANTS['ID_KDEBUG']]
    for name, field in (('IMAGE_MAX', 'image_max'), ('RELOC_MAX', 'reloc_max'),
                        ('IMPORT_MAX', 'import_max'), ('EXPORT_MAX', 'export_max'),
                        ('OPS_SLOTS', 'ops_slots')):
        lines.append(f'#define MODULE_{name} {kdebug[field]}U')
    lines += ['', '/* Wire word numbers; decode little-endian bytes explicitly. */',
              'enum module_field {']
    lines += [f'    MI_{name} = {index},' for index, name in enumerate(HEADER_FIELDS)]
    lines += [f'    MI_WORDS = {len(HEADER_FIELDS)}', '};', '',
              '#define MODULE_COMPONENT_POLICIES { \\']
    for policy in POLICIES.values():
        lines.append('    { \\')
        lines += [f'        .{field} = {policy[field]}U, \\' for field in POLICY_FIELDS]
        lines.append('    }, \\')
    lines += ['}', '', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, 'KMOD schema stale: run python3 tools/gen_module_schema.py\n')
    elif not OUTPUT.exists() or OUTPUT.read_text() != expected:
        OUTPUT.write_text(expected)


if __name__ == '__main__':
    main()
