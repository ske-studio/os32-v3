#!/usr/bin/env python3
"""TASK_FONTPERF F1: collect the Full-cell characters of the GUI's own strings.

  python3 tools/g16/scan_ui_chars.py            # rewrites tools/g16/ui_chars.txt
  python3 tools/g16/scan_ui_chars.py --check    # rc 1 if the file is stale

Run by hand and commit the result (design §4): the bundle's preload list must
not move with every wording change, so the build only reads ui_chars.txt.

Source: Rust string and char literals (comments are skipped) under
userland/gshell/src, userland/rust/libos32gui/src, userland/*/src and the GUI
apps userland/rust/*/src. Kept: code points on the engine's Full path
(cp >= 0x80, not U+00A0..U+024F; font crate engine.rs is_latin_half).
Output: one `XXXX  c` line per code point, sorted.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / 'ui_chars.txt'
GLOBS = ('userland/gshell/src/**/*.rs', 'userland/rust/libos32gui/src/**/*.rs',
         'userland/*/src/**/*.rs', 'userland/rust/*/src/**/*.rs')
LATIN_HALF_FIRST = 0xA0  # font crate limits.rs
LATIN_HALF_LAST = 0x24F


def full_path(cp):
    return cp >= 0x80 and not (LATIN_HALF_FIRST <= cp <= LATIN_HALF_LAST)


def literals(text):
    """Yield the raw bodies of string/char literals of Rust source (comments skipped)."""
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith('//', i):
            j = text.find('\n', i)
            i = n if j < 0 else j
        elif text.startswith('/*', i):
            depth, i = 1, i + 2
            while i < n and depth:
                if text.startswith('/*', i):
                    depth, i = depth + 1, i + 2
                elif text.startswith('*/', i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
        elif c == 'r' and (text.startswith('r"', i) or text.startswith('r#', i)) and (
                i == 0 or not (text[i - 1].isalnum() or text[i - 1] == '_')):
            j = i + 1
            while j < n and text[j] == '#':
                j += 1
            if j >= n or text[j] != '"':
                i += 1
                continue
            end = '"' + '#' * (j - i - 1)
            k = text.find(end, j + 1)
            k = n if k < 0 else k
            yield text[j + 1:k]
            i = k + len(end)
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == '\\' else 1
            yield text[i + 1:j]
            i = j + 1
        elif c == "'":
            # char literal ('x', '\n', '\u{..}') vs lifetime/label ('a)
            if i + 2 < n and text[i + 1] != '\\' and text[i + 2] == "'":
                yield text[i + 1]
                i += 3
            elif text.startswith("'\\", i):
                k = text.find("'", i + 2)
                yield text[i + 1:k]
                i = k + 1
            else:
                i += 1
        else:
            i += 1


def scan(root=ROOT):
    files = sorted({p for g in GLOBS for p in root.glob(g)})
    found = set()
    for path in files:
        for body in literals(path.read_text(encoding='utf-8')):
            found.update(ord(ch) for ch in body if full_path(ord(ch)))
    return sorted(found), len(files)


def render(cps):
    head = ('# TASK_FONTPERF: Full-cell characters of the GUI string literals.\n'
            '# Generated by tools/g16/scan_ui_chars.py (run by hand, commit the result).\n')
    return head + ''.join('%04X  %s\n' % (cp, chr(cp)) for cp in cps)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='compare with the committed file')
    args = ap.parse_args(argv)
    cps, nfiles = scan()
    text = render(cps)
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding='utf-8') == text
        print('scan_ui_chars: %d chars from %d files, %s' % (len(cps), nfiles, 'up to date' if same else 'STALE'))
        return 0 if same else 1
    OUT.write_text(text, encoding='utf-8')
    print('scan_ui_chars: %d chars from %d files -> %s' % (len(cps), nfiles, OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
