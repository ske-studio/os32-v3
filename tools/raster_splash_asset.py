#!/usr/bin/env python3
"""Explicit one-image asset generation; never invoked by the normal build."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import struct
import subprocess
import tempfile

import numpy as np
from PIL import __version__ as pillow_version
from osri_enc2_decode import decode
from osri_profile import OSRI_DEFAULT_OUT_BUDGET

ROOT = Path(__file__).resolve().parents[1]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def statistics(data):
    _, _, _, outs = decode(data, budget=OSRI_DEFAULT_OUT_BUDGET)
    return dict(sha256=sha(data), crc32=f'{struct.unpack_from("<I", data, 48)[0]:08x}',
                bytes=len(data), events=struct.unpack_from('<I', data, 36)[0],
                max_outs=max(outs), total_outs=sum(outs))


def generate(source, output, reference, *, threads=None, replace=False):
    source, output, reference = map(lambda p: Path(p).resolve(), (source, output, reference))
    manifest = output.with_suffix('.manifest.json')
    if output in (source, reference) or manifest in (source, reference):
        raise ValueError('output must not replace the source or reference')
    if not replace and (output.exists() or manifest.exists()):
        raise ValueError('existing output requires --replace')
    workers = (os.cpu_count() or 1) if threads is None else threads
    if workers < 1:
        raise ValueError('threads must be positive')
    inputs = ['tools/img2osri.py', 'gfx/osri_profile.h']
    inputs += [str(p.relative_to(ROOT)) for p in sorted((ROOT / 'tools').glob('osri_*'))
               if p.is_file()]
    if subprocess.check_output(['git', 'diff', 'HEAD', '--', *inputs], cwd=ROOT):
        raise ValueError('generator inputs must match a committed version')
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    original = source.read_bytes()
    baseline = reference.read_bytes()
    statistics(baseline)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.splash-', dir=output.parent) as td:
        candidate = Path(td) / output.name
        arguments = ['--encoder', 'enc2', '--outs', str(OSRI_DEFAULT_OUT_BUDGET),
                     '--band', '1', '--threads', str(workers)]
        subprocess.run(['python3', '-B', str(ROOT / 'tools/img2osri.py'), str(source),
                        '-o', str(candidate), *arguments], check=True)
        data = candidate.read_bytes()
        stats = statistics(data)
        if data != baseline:
            raise ValueError('generated bytes differ from the accepted reference')
        if source.read_bytes() != original:
            raise ValueError('source changed during generation')
        record = dict(source_sha256=sha(original), generator_commit=commit,
                      generator_inputs={p: sha((ROOT / p).read_bytes()) for p in inputs},
                      arguments=arguments, threads=workers,
                      libraries=dict(Python=platform.python_version(), Pillow=pillow_version,
                                     NumPy=np.__version__), output=stats)
        sidecar = Path(td) / manifest.name
        sidecar.write_text(json.dumps(record, indent=2, sort_keys=True) + '\n')
        candidate.replace(output)
        sidecar.replace(manifest)
    return record


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('input')
    p.add_argument('-o', '--output', required=True)
    p.add_argument('--reference', required=True, help='accepted baseline; compare every byte')
    p.add_argument('--threads', type=int)
    p.add_argument('--replace', action='store_true')
    args = p.parse_args()
    try:
        record = generate(args.input, args.output, args.reference,
                          threads=args.threads, replace=args.replace)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        p.exit(1, f'asset: {exc}\n')
    print(json.dumps(record['output'], sort_keys=True))


if __name__ == '__main__':
    main()
