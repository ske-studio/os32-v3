class MissingMap(Exception):
    pass


def read_symbols(map_path):
    """kernel.map から __bss_end などを取る。無ければ **止まる** (推測しない)。"""
    if not os.path.isfile(map_path):
        raise MissingMap(
            "%s が無い。__bss_end はカーネルを積んだ結果でしか決まらないので、\n"
            "ここで推測すると地図がそれらしい嘘になる (票 §4-bis)。\n"
            "先に `make CROSS_DIR=... kernel` を実行してから、もう一度呼ぶこと。"
            % map_path)
    want = dict.fromkeys(SYMBOLS)
    with open(map_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.search(r"0x([0-9a-fA-F]+)\s+(\w+)\s*=", line)
            if m and m.group(2) in want and want[m.group(2)] is None:
                want[m.group(2)] = int(m.group(1), 16)
    missing = [k for k, v in want.items() if v is None]
    if missing:
        raise MissingMap("%s に %s が無い。リンカスクリプトが変わった可能性がある。"
                         % (map_path, " / ".join(missing)))
    return want


DEFINE = re.compile(r"^\s*#define\s+([A-Za-z_]\w*)\s+(\S.*?)\s*$")
IDENT = re.compile(r"\b([A-Za-z_]\w*)\b")
CASTS = re.compile(r"\((?:u8|u16|u32|int|unsigned|long)\)")
SUFFIX = re.compile(r"\b(0[xX][0-9a-fA-F]+|\d+)[uU]?[lL]*\b")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def read_defines(header_path, layout=0):
    """#define NAME expr を集める (行継続をつないでからコメントを落とす)。"""
    with open(header_path, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"\\\n", " ", text)
    # Use the C preprocessor for the selected branch. Includes carry types only;
    # omit them so isolated header fixtures need no copy of the include tree.
    if os.path.basename(header_path) == "memmap.h":
        source = re.sub(r'^\s*#include[^\n]*', '', text, flags=re.M)
        text = subprocess.run(["cpp", "-dM", "-E", "-x", "c",
                               "-DMEM_LAYOUT_V5=" + str(layout), "-"],
                              input=source, text=True, capture_output=True,
                              check=True).stdout
    out = {}
    for line in strip_comments(text).split("\n"):
        m = DEFINE.match(line)
        if m and "(" not in m.group(1):
            out[m.group(1)] = m.group(2).strip()
    return out


def write_layout_header(root, path, layout):
    """One C-preprocessor input for C, linker scripts and NASM sources.

    Prefix macros so ld can still export the original names as ELF symbols.
    Keep linker references as expressions; never invent floating addresses.
    """
    defines = read_defines(os.path.join(root, HDR_REL), layout)
    names = sorted(n for n in defines if n.startswith("MEM_") or
                   n in ("KERNEL_LOAD_ADDR", "KHEAP_BASE", "KHEAP_SIZE"))
    lines = ["/* Generated by tools/gen_memmap.py; do not edit. */"]
    constants = Macros(defines, {})
    for name in names:
        expr = re.sub(r"\(\s*u32\s*\)\s*&\s*(\w+)", r"\1", defines[name])
        expr = SUFFIX.sub(r"\1", expr)
        expr = IDENT.sub(lambda m: "LAYOUT_" + m[0] if m[0] in names else m[0], expr)
        value = constants.get(name)
        if value is not None:
            expr = "0x%X" % value
        lines.append("#define LAYOUT_%s %s" % (name, expr))
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


def selected_layout_defects(root, elf_path, header_path, layout):
    """Reject an ELF/header/selected source mixture, including floating values."""
    _, symbols = read_elf(elf_path)
    source = Macros(read_defines(os.path.join(root, HDR_REL), layout), symbols)
    generated = Macros(read_defines(header_path), symbols)
    out = []
    if symbols.get("MEM_LAYOUT_V5") != layout:
        out.append("ELF layout selection mismatch")
    for name in source.defines:
        if not (name.startswith("MEM_") or name in ("KERNEL_LOAD_ADDR", "KHEAP_BASE", "KHEAP_SIZE")):
            continue
        expected = source.get(name)
        actual = generated.get("LAYOUT_" + name)
        if expected is None or actual != expected:
            out.append("generated layout mismatch: " + name)
        if name in symbols and symbols[name] != expected:
            out.append("ELF layout value mismatch: " + name)
    return out


def preprocess_layout(root, source, layout=0, traditional=False):
    """Preprocess a linker/NASM fixture by the same header as Make."""
    with tempfile.TemporaryDirectory(prefix="memmap-cpp-") as work:
        header = os.path.join(work, "memmap_layout.h")
        write_layout_header(root, header, layout)
        cmd = ["cpp", "-E", "-P", "-x", "c", "-I" + work, "-imacros", header]
        if traditional:
            cmd.append("-traditional-cpp")
        return subprocess.run(cmd + ["-"], input=source, text=True,
                              capture_output=True, check=True).stdout


class Macros(object):
    """#define を必要になった順に解く。解けないものは None のまま置く。"""

    def __init__(self, defines, symbols):
        self.defines = defines
        self.symbols = symbols
        self.cache = {}
        self.busy = set()

    def get(self, name):
        if name in self.cache:
            return self.cache[name]
        if name in self.busy or name not in self.defines:
            return None
        self.busy.add(name)
        try:
            value = self._eval(self.defines[name])
        finally:
            self.busy.discard(name)
        self.cache[name] = value
        return value

    def _eval(self, expr):
        # (u32)&__bss_end のようなリンカシンボル参照を実値に置き換える
        def sym(m):
            v = self.symbols.get(m.group(1))
            return str(v) if v is not None else "None"
        expr = re.sub(r"\(\s*u32\s*\)\s*&\s*(\w+)", sym, expr)
        expr = re.sub(r"&\s*(\w+)", sym, expr)
        expr = CASTS.sub("", expr)
        expr = SUFFIX.sub(r"\1", expr)
        names = set(IDENT.findall(expr)) - {"None"}
        for n in names:
            if re.match(r"^0[xX]", n):
                continue
            v = self.symbols[n] if n in self.symbols else self.get(n)
            if v is None:
                return None
            expr = re.sub(r"\b%s\b" % re.escape(n), "(%d)" % v, expr)
        expr = re.sub(r"(?<![/])/(?![/])", "//", expr)
        try:
            return int(eval(expr, {"__builtins__": {}}, {}))  # noqa: S307
        except Exception:
            return None


