"""Extract fmgen integer tables on the host; --check also executes the Rust constants."""
import argparse
import hashlib
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'lib/os32_opna'
TABLES = CORE / 'src/tables.rs'


def extract(source, work):
    # fmgen_types.h defines the needed integer aliases itself.
    (work / 'compiler.h').touch()
    binary = work / 'extract'
    subprocess.run(['g++', '-std=c++17', '-DSUPPORT_FMGEN', '-DMAX_PATH=260',
                    '-I', work, '-I', source, '-ffunction-sections', '-fdata-sections',
                    '-Wl,--gc-sections', ROOT / 'tools/gen_opna_tables.cpp',
                    *(source / f'fmgen_{name}.cpp' for name in ('fmgen', 'opna', 'psg', 'fmtimer')),
                    '-o', binary], check=True)
    return subprocess.check_output([binary], text=True).splitlines()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=CORE / 'upstream')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--mutate', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        rust = ['// Generated by tools/gen_opna_tables.py. Row-major order.']
        manifest = ['# name type length sha256(little-endian elements)']
        harness = ['mod tables;', 'use std::io::{self, Write};',
                   'fn main() { let mut out = io::BufWriter::new(io::stdout().lock());']
        expected = bytearray()
        for line in extract(args.source, work):
            name, kind, *digits = line.split()
            data = b''.join(int(x).to_bytes(int(kind[1:]) // 8, 'little',
                                            signed=kind.startswith('i')) for x in digits)
            expected.extend(data)
            manifest.append(f'{name} {kind} {len(digits)} {hashlib.sha256(data).hexdigest()}')
            rust.append(f'pub static {name}: [{kind}; {len(digits)}] = [')
            for i in range(0, len(digits), 16):
                rust.append('    ' + ', '.join(digits[i:i + 16]) + ',')
            rust.append('];')
            harness.append(f'for v in &tables::{name} {{ out.write_all(&v.to_le_bytes()).unwrap(); }}')
        manifest_text = '\n'.join(manifest) + '\n'
        manifest_path = CORE / 'tables.manifest'
        if not args.check:
            TABLES.write_text('\n'.join(rust) + '\n')
            manifest_path.write_text(manifest_text)
            return
        if manifest_path.read_text() != manifest_text:
            raise SystemExit('table manifest differs from fmgen')
        (work / 'main.rs').write_text('\n'.join(harness + ['}']))
        source = TABLES.read_text()
        def compare(contents):
            (work / 'tables.rs').write_text(contents)
            subprocess.run(['rustc', work / 'main.rs', '-o', work / 'dump'], check=True)
            return subprocess.check_output([work / 'dump']) == expected
        if not compare(source):
            raise SystemExit('Rust table values differ from fmgen')
        print(f'{len(manifest) - 1} tables, {len(expected)} bytes match fmgen')
        if args.mutate:
            import re
            pattern = r'(pub static SINE:[^=]+=\s*\[\s*)(\d+)'
            mutated, count = re.subn(pattern, lambda m: m[1] + str(int(m[2]) ^ 1), source)
            if count != 1 or compare(mutated):
                raise SystemExit('SINE mutation failed')
            print('RED: SINE[0] differs from fmgen')


if __name__ == '__main__':
    main()
