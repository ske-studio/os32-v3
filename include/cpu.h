/* ======================================================================== */
/*  CPU.H — アドレス空間の切替と特権レベルの境界の **契約**                  */
/*                                                                          */
/*  MMU (変換表の根の読み書き・TLB・変換の有効化) と、カーネルから           */
/*  ユーザモードへ降りる / 別スタックで入口を呼ぶ遷移について、カーネルが     */
/*  「何を保証されるか」だけをここに書く。**実装は一切ここに無い。**          */
/*                                                                          */
/*  実装は CPU の持ち物なので arch 軸だけで選ぶ (build/config.mk):           */
/*                                                                          */
/*    arch/$(ARCH)/arch_cpu.h         既定 ARCH = x86                        */
/*                                                                          */
/*  取り込む名前は **固定** (`arch_cpu.h`) で、どの実装が来るかは            */
/*  `-Iarch/$(ARCH)` が決める。作法は include/io.h と同じ (arch/README.md)。  */
/*                                                                          */
/*  カーネル側の C ソースは制御レジスタ (x86 なら CR0 / CR3) やリング遷移を   */
/*  その場の asm で書かない。ここの原始命令だけを使う。                      */
/*                                                                          */
/*  下の宣言に付いた註は「何を保証するか」の契約であって x86 の説明ではない。 */
/*  別アーキテクチャへ移すときは、命令列ではなく **契約** を再現すること。    */
/*                                                                          */
/*  契約に入れていないもの: GDT のロードとセグメントの再設定、タスクレジスタ  */
/*  のロード。これは x86 にしか無い仕組みで、他の CPU に「同じ意味」が無い。  */
/*  x86 だけの arch/x86/kernel/gdt.c / arch/x86/kernel/tss.c が arch/x86/x86_desc.h を直接引く。 */
/* ======================================================================== */

#ifndef CPU_H
#define CPU_H

#include "abi.h"

#ifndef __ASSEMBLER__
#include "types.h"

/* ======================================================================== */
/*  1. アドレス空間 (MMU)                                                   */
/*                                                                          */
/*  OS32 のアドレス空間は「変換表の根」1 つの物理番地で表す (x86 なら       */
/*  ページディレクトリ、ARM なら TTBR が指す第 1 段の表)。根の形そのものは   */
/*  arch 固有で、ここでは番地を不透明な u32 として受け渡すだけ。             */
/* ======================================================================== */

/* いま CPU に載っている変換表の根の物理番地を返す。
 * 契約: 直前の arch_mmu_load_root() に渡した値がそのまま返る
 *       (下位の属性ビットを CPU が足す arch では、それを落として返すこと)。 */
static inline u32 arch_mmu_current_root(void);

/* 変換表の根を切り替える。
 * 契約: 戻った時点で、以後のメモリアクセスは `root_phys` の表で変換される。
 *       **切替前の空間の変換は TLB に残らない** — 同じ根を載せ直した場合も
 *       含む (呼び手は「同じ根の再ロード」を TLB の全消去として使っている:
 *       mm/paging.c)。ASID を持つ CPU で TLB を残す実装にするなら、
 *       呼び手の側を arch_mmu_flush_tlb() に書き換えてからにすること。 */
static inline void arch_mmu_load_root(u32 root_phys);

/* いまの空間の TLB を全部捨てる。
 * 契約: 戻った時点で、変換表への直前の書き換えがすべて見える。
 *       根は変えない。1 ページだけ捨てる命令が使える CPU でも、これは
 *       **全部**を捨てる (呼び手は複数ページをまとめて書き換えた後に呼ぶ)。 */
static inline void arch_mmu_flush_tlb(void);

/* アドレス変換を有効にする。
 * 契約: 呼ぶ前に arch_mmu_load_root() で根が載っていること。いま実行中の
 *       番地は恒等マップされていること (有効化の直後の命令を同じ番地で
 *       取り出すため)。変換以外の CPU 設定には触らない。ブートで 1 回だけ。 */
static inline void arch_mmu_enable(void);

/* ======================================================================== */
/*  2. 実装の取り込み                                                       */
/*                                                                          */
/*  固定名を引き、-I で実装を選ぶ。ファイル名が "cpu.h" と違うのは、         */
/*  実装側が誤ってこの契約ヘッダ自身を引き込まないようにするため。           */
/* ======================================================================== */

#include "arch_cpu.h"       /* arch/$(ARCH)/arch_cpu.h */

#endif /* !__ASSEMBLER__ */
#endif /* CPU_H */
