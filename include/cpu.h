/* ======================================================================== */
/*  CPU.H — アドレス空間の切替と特権レベルの境界の **契約**                  */
/*                                                                          */
/*  MMU (変換表の根の読み書き・TLB・変換の有効化) と、カーネルから           */
/*  ユーザモードへ降りる / 別スタックで入口を呼ぶ遷移について、カーネルが     */
/*  「何を保証されるか」だけをここに書く。**実装は一切ここに無い。**          */
/*                                                                          */
/*  実装は CPU の持ち物なので arch 軸だけで選ぶ (build/config.mk):           */
/*                                                                          */
/*    arch/$(ARCH)/arch_cpu.h         既定 ARCH = x86                        */
/*                                                                          */
/*  取り込む名前は **固定** (`arch_cpu.h`) で、どの実装が来るかは            */
/*  `-Iarch/$(ARCH)` が決める。作法は include/io.h と同じ (arch/README.md)。  */
/*                                                                          */
/*  カーネル側の C ソースは制御レジスタ (x86 なら CR0 / CR3) やリング遷移を   */
/*  その場の asm で書かない。ここの原始命令だけを使う。                      */
/*                                                                          */
/*  下の宣言に付いた註は「何を保証するか」の契約であって x86 の説明ではない。 */
/*  別アーキテクチャへ移すときは、命令列ではなく **契約** を再現すること。    */
/*                                                                          */
/*  契約に入れていないもの: GDT のロードとセグメントの再設定、タスクレジスタ  */
/*  のロード。これは x86 にしか無い仕組みで、他の CPU に「同じ意味」が無い。  */
/*  x86 だけの kernel/gdt.c / kernel/tss.c が arch/x86/x86_desc.h を直接引く。 */
/* ======================================================================== */

#ifndef CPU_H
#define CPU_H

#include "types.h"

/* ======================================================================== */
/*  1. アドレス空間 (MMU)                                                   */
/*                                                                          */
/*  OS32 のアドレス空間は「変換表の根」1 つの物理番地で表す (x86 なら       */
/*  ページディレクトリ、ARM なら TTBR が指す第 1 段の表)。根の形そのものは   */
/*  arch 固有で、ここでは番地を不透明な u32 として受け渡すだけ。             */
/* ======================================================================== */

/* いま CPU に載っている変換表の根の物理番地を返す。
 * 契約: 直前の arch_mmu_load_root() に渡した値がそのまま返る
 *       (下位の属性ビットを CPU が足す arch では、それを落として返すこと)。 */
static inline u32 arch_mmu_current_root(void);

/* 変換表の根を切り替える。
 * 契約: 戻った時点で、以後のメモリアクセスは `root_phys` の表で変換される。
 *       **切替前の空間の変換は TLB に残らない** — 同じ根を載せ直した場合も
 *       含む (呼び手は「同じ根の再ロード」を TLB の全消去として使っている:
 *       kernel/paging.c)。ASID を持つ CPU で TLB を残す実装にするなら、
 *       呼び手の側を arch_mmu_flush_tlb() に書き換えてからにすること。 */
static inline void arch_mmu_load_root(u32 root_phys);

/* いまの空間の TLB を全部捨てる。
 * 契約: 戻った時点で、変換表への直前の書き換えがすべて見える。
 *       根は変えない。1 ページだけ捨てる命令が使える CPU でも、これは
 *       **全部**を捨てる (呼び手は複数ページをまとめて書き換えた後に呼ぶ)。 */
static inline void arch_mmu_flush_tlb(void);

/* アドレス変換を有効にする。
 * 契約: 呼ぶ前に arch_mmu_load_root() で根が載っていること。いま実行中の
 *       番地は恒等マップされていること (有効化の直後の命令を同じ番地で
 *       取り出すため)。変換以外の CPU 設定には触らない。ブートで 1 回だけ。 */
static inline void arch_mmu_enable(void);

/* ======================================================================== */
/*  2. 特権レベルの境界                                                     */
/*                                                                          */
/*  この 2 つだけは static inline 関数ではなく **マクロ** として実装する。   */
/*  関数にすると (1) 退避先のスロットがポインタ引数になり、呼び手が持って    */
/*  いた添字つきの番地計算がレジスタに乗って割り付けが動く、(2) asm が       */
/*  呼び手の基本ブロックから出て分岐の並びが変わる — どちらも動作は同じだが  */
/*  生成物が変わり、「移設で命令列は変わっていない」を .o の md5 で示せなく  */
/*  なる (実測: 順序 5)。引数の意味と契約は下に書く。マクロなので宣言は      */
/*  置けない (置くと実装がマクロの arch で「定義の無い static」になる)。     */
/* ======================================================================== */

/* カーネルからユーザモードへ降りて `entry` から走らせる。**戻らない。**
 * 契約 (この順序は不可分で、途中で割り込みを受け付けない):
 *   1. 割り込みを禁止する。
 *   2. いまのカーネルのスタックポインタを、その CPU が「ユーザモードから
 *      戻るときのカーネルスタック」を探す場所に記録する (x86 では
 *      TSS.ESP0)。置き場は arch 固有なので引数にしていない。以後ユーザ
 *      モードから割り込み・例外・システムコールで戻るとき、CPU はこの
 *      スタックの上にフレームを積む。
 *   3. 変換表の根を `root_phys` に切り替える (arch_mmu_load_root と同じ意味)。
 *   4. ユーザモードのデータ/スタック用のセグメント・レジスタ類をユーザの
 *      ものにする (その概念の無い CPU では何もしない)。
 *   5. スタックポインタ = `user_sp`、プログラムカウンタ = `entry`、
 *      **割り込み許可**・I/O 特権なし、でユーザモードに入る。割り込みの
 *      許可はユーザモードに入るのと同時に効く (カーネル側で許可された
 *      瞬間は無い)。
 * 途中に割り込みが入ると、2 で記録したスタックと 3 の根が食い違った状態で
 * ハンドラが走る。だから **1〜5 を 1 つの原始命令として実装する** こと。
 * 割り込み許可の出口の扱いは docs/POLICY_DEBUG.md §4-19。
 * 終了はここから戻るのではなく、システムコール → longjmp で行う。
 * 「戻らない」ことをコンパイラに教えては **いけない** (noreturn 相当の印を
 * 付けると呼び手の後続コードが消え、移設前と生成物が変わる)。
 *
 *     arch_enter_user(u32 root_phys, u32 user_sp, u32 entry)   マクロ */

/* 特権レベルを変えずに、スタックを `new_sp` に切り替えて `entry` を呼ぶ。
 * 契約:
 *   - 呼ぶ前に、いまのスタックポインタを `saved_sp_slot` に書く
 *     (**左辺値**を渡す。マクロなので `&` は要らない)。
 *   - `entry` は `new_sp` をスタックポインタとして呼ばれる。引数は呼び手が
 *     `new_sp` の上に呼出規約どおり積んでおく (この関数は何も積まない)。
 *   - `entry` から戻ったら、スタックポインタを `saved_sp_slot` から戻す。
 *     スロットはローカル変数であってはいけない (切替後のスタックからは
 *     フレームポインタ相対で読めない)。
 *   - `entry` が戻らず longjmp で抜けてもよい (その場合ここも戻らない)。
 *   - 呼出規約で呼ばれた側が壊してよいレジスタは壊れてよい。
 *
 *     arch_call_on_stack(u32 saved_sp_slot, u32 new_sp, u32 entry)  マクロ */

/* ======================================================================== */
/*  3. 実装の取り込み                                                       */
/*                                                                          */
/*  固定名を引き、-I で実装を選ぶ。ファイル名が "cpu.h" と違うのは、         */
/*  実装側が誤ってこの契約ヘッダ自身を引き込まないようにするため。           */
/* ======================================================================== */

#include "arch_cpu.h"       /* arch/$(ARCH)/arch_cpu.h */

#endif /* CPU_H */
