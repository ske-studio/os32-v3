/*  ENDIAN_LE.H — 外部形式 (リトルエンディアン) の読み書き **契約**          */
/*                                                                          */
/*  ディスク上・ワイヤ上の構造は「バイトの並び」で決まっていて、CPU の       */
/*  バイト順やアラインメントの都合とは関係が無い。ここの 4 つは、その並びを   */
/*  **1 バイトずつ**組み立て / 分解する。だから                             */
/*                                                                          */
/*    * どのバイト順の CPU でも同じ値になる (LE 固定)                        */
/*    * どの番地からでも読める (u8 のアクセスしかしない)                     */
/*                                                                          */
/*  `*(u32 *)&buf[off]` は x86 でしか成り立たない書き方で、2 つの前提を      */
/*  同時に隠してしまう — CPU が LE であること、非アラインアクセスが許される   */
/*  こと。ARM (SCTLR.A=1) や MIPS では前者で値が化け、後者で落ちる。         */
/*  外部形式を触る場所では必ずここを通すこと。                               */
/*                                                                          */
/*  対象は「媒体・回線の上に並ぶバイト列」だけ。カーネル内のメモリ構造        */
/*  (u32 の配列やメンバ) は、その CPU の自然な並びで置いてあるので対象外。    */
/*                                                                          */
/*  番人は tools/check_le_access.py (make check)。対象ファイルを             */
/*  `-Wcast-align=strict` で単体コンパイルし、警告 0 を要求する。            */
/*  GCC の既定の `-Wcast-align` は「非アラインを許す CPU」では黙るので、      */
/*  x86 のホストで見張るには `=strict` が要る。                              */
/*                                                                          */
/*  実装が `static inline` の純 C なのは、カーネル (i386-elf-gcc) と         */
/*  ホスト試験 (gcc -m32。fs/ の .c をソースごと取り込む) の両方から          */
/*  同じ 1 枚を引くため。-O2 では x86 で 1 命令の load/store に畳まれる。     */
/* ======================================================================== */

#ifndef ENDIAN_LE_H
#define ENDIAN_LE_H

#include "types.h"

/* 16-bit LE を読む。
 * 契約: p[0] が最下位バイト。p は任意の番地でよい。 */
static inline u16 le16_rd(const void *p)
{
    const u8 *b = (const u8 *)p;
    return (u16)((u16)b[0] | (u16)((u16)b[1] << 8));
}

/* 16-bit LE を書く。
 * 契約: p[0] に最下位バイト。p は任意の番地でよい。2 バイトを書く。 */
static inline void le16_wr(void *p, u16 v)
{
    u8 *b = (u8 *)p;
    b[0] = (u8)(v & 0xFFu);
    b[1] = (u8)((v >> 8) & 0xFFu);
}

/* 32-bit LE を読む。
 * 契約: p[0] が最下位バイト。p は任意の番地でよい。4 バイトを読む。 */
static inline u32 le32_rd(const void *p)
{
    const u8 *b = (const u8 *)p;
    return (u32)b[0] | ((u32)b[1] << 8) | ((u32)b[2] << 16) | ((u32)b[3] << 24);
}

/* 32-bit LE を書く。
 * 契約: p[0] に最下位バイト。p は任意の番地でよい。4 バイトを書く。 */
static inline void le32_wr(void *p, u32 v)
{
    u8 *b = (u8 *)p;
    b[0] = (u8)(v & 0xFFu);
    b[1] = (u8)((v >> 8) & 0xFFu);
    b[2] = (u8)((v >> 16) & 0xFFu);
    b[3] = (u8)((v >> 24) & 0xFFu);
}

#endif /* ENDIAN_LE_H */
