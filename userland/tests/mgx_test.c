static void test_malformed(void)
{
    MgxHeader h, t;
    u8 bad[MGX_HDR_SIZE];
    u8 *corrupt;
    int rc;

    header("malformed input");

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[0] = 'X';
    check_eq("bad magic", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_MAGIC);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[4] = 99;
    check_eq("bad version", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_VERSION);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[6] = 0xFF; bad[7] = 0xFF;
    check_eq("width overflow", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_HEADER);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[10] = 77;
    check_eq("bad codec", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_CODEC);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[20] = 5;
    check_eq("bad bpp", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_HEADER);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[21] = 9;
    check_eq("npal mismatch", mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_HEADER);

    memcpy(bad, mgx4_zlib, MGX_HDR_SIZE); bad[20] = 3; bad[21] = 8;
    check_eq("bpp/raw_size mismatch",
             mgx_parse_header(bad, MGX_HDR_SIZE, &t), MGX_ERR_HEADER);

    check_eq("short header", mgx_parse_header(mgx4_zlib, 8, &t), MGX_ERR_TRUNC);
    check_eq("null buf", mgx_parse_header(0, MGX_HDR_SIZE, &t), MGX_ERR_ARG);

    mgx_parse_header(mgx4_zlib, sizeof(mgx4_zlib), &h);
    rc = mgx_decode(&h, mgx4_zlib + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx4_zlib) - MGX_HDR_SIZE),
                    workbuf, TEST_RAW4 - 1);
    check_eq("dst too small", rc, MGX_ERR_SIZE);

    rc = mgx_decode(&h, mgx4_zlib + MGX_HDR_SIZE, 4, workbuf, sizeof(workbuf));
    check_eq("payload truncated", rc, MGX_ERR_TRUNC);

    corrupt = workbuf + TEST_RAW4 * 2;
    memcpy(corrupt, mgx4_zlib + MGX_HDR_SIZE, h.data_size);
    corrupt[h.data_size / 2] ^= 0xFF;
    rc = mgx_decode(&h, corrupt, h.data_size, workbuf, TEST_RAW4);
    check("corrupt stream rejected",
          rc == MGX_ERR_STREAM || rc == MGX_ERR_CKSUM || rc == MGX_ERR_SIZE);

    memcpy(corrupt, mgx4_zlib + MGX_HDR_SIZE, h.data_size);
    corrupt[1] ^= 0x01;
    rc = mgx_decode(&h, corrupt, h.data_size, workbuf, TEST_RAW4);
    check_eq("bad zlib header", rc, MGX_ERR_STREAM);
}

