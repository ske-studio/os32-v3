/* 4 プレーンから 1 画素の階調インデックス (0..15) を取り出す */
static int pixel_index(const u8 *planes, int pitch, int x, int y)
{
    int p, v = 0;
    int off = y * pitch + (x >> 3);
    int bit = 0x80 >> (x & 7);

    for (p = 0; p < 4; p++) {
        if (planes[p * (pitch * TEST_H) + off] & bit)
            v |= (1 << p);
    }
    return v;
}

