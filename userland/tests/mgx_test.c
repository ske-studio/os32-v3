static void test_header(void)
{
    MgxHeader h;
    int rc, i, seen[16], ok;

    header("header / palette table");

    rc = mgx_parse_header(mgx4_zlib, sizeof(mgx4_zlib), &h);
    check_eq("parse(bpp4) rc", rc, MGX_OK);
    check_eq("hdr size", MGX_HDR_SIZE, 48);
    check_eq("width", h.width, TEST_W);
    check_eq("height", h.height, TEST_H);
    check_eq("bpp", h.bpp, 4);
    check_eq("npal", h.npal, 16);
    check_eq("raw_size", (int)h.raw_size, TEST_RAW4);
    check_eq("pitch", mgx_pitch(&h), TEST_PITCH);
    check_eq("plane_size", (int)mgx_plane_size(&h), TEST_PLANE);

    for (i = 0; i < 16; i++) seen[i] = 0;
    for (i = 0; i < 16; i++) seen[h.palette[i] & 15]++;
    ok = 1;
    for (i = 0; i < 16; i++) if (seen[i] != 1) ok = 0;
    check("palette is a bijection", ok);

    ok = 1;
    for (i = 0; i < 16; i++)
        if (h.palette[i ^ (i >> 1)] != i) ok = 0;
    check("palette is the gray-code inverse", ok);

    /* 余白は表示上いちばん明るい番号。Gray 表なら階調 15 は index 15^7 = 8 */
    check_eq("paper index", mgx_paper_index(&h, 0), 8);
    check_eq("paper index (inverted)", mgx_paper_index(&h, 1), 0);

    rc = mgx_parse_header(mgx4_linear, sizeof(mgx4_linear), &h);
    check_eq("parse(bpp4 linear) rc", rc, MGX_OK);
    ok = 1;
    for (i = 0; i < 16; i++) if (h.palette[i] != i) ok = 0;
    check("linear palette is identity", ok);
    check_eq("linear paper index", mgx_paper_index(&h, 0), 15);

    rc = mgx_parse_header(mgx1_zlib, sizeof(mgx1_zlib), &h);
    check_eq("parse(bpp1) rc", rc, MGX_OK);
    check_eq("bpp1", h.bpp, 1);
    check_eq("bpp1 npal", h.npal, 2);
    check_eq("bpp1 paper level", h.palette[0], 15);
    check_eq("bpp1 ink level", h.palette[1], 0);
    check_eq("bpp1 paper index", mgx_paper_index(&h, 0), 0);
    check_eq("bpp1 paper index (inv)", mgx_paper_index(&h, 1), 1);
}

