static void test_decode(void)
{
    MgxHeader h, hl;
    int rc, x, y, same;
    u8 *lin;

    header("decode");

    mgx_parse_header(mgx4_zlib, sizeof(mgx4_zlib), &h);
    memset(workbuf, 0, sizeof(workbuf));
    rc = mgx_decode(&h, mgx4_zlib + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx4_zlib) - MGX_HDR_SIZE),
                    workbuf, sizeof(workbuf));
    check_eq("decode(bpp4) bytes", rc, TEST_RAW4);
    check("decode(bpp4) content", memcmp(workbuf, expect_raw4, TEST_RAW4) == 0);
    check("decode(bpp4) no overrun",
          workbuf[TEST_RAW4] == 0 && workbuf[TEST_RAW4 + 1] == 0);

    mgx_parse_header(mgx1_zlib, sizeof(mgx1_zlib), &h);
    memset(workbuf, 0, sizeof(workbuf));
    rc = mgx_decode(&h, mgx1_zlib + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx1_zlib) - MGX_HDR_SIZE),
                    workbuf, sizeof(workbuf));
    check_eq("decode(bpp1) bytes", rc, TEST_RAW1);
    check("decode(bpp1) content", memcmp(workbuf, expect_raw1, TEST_RAW1) == 0);

    mgx_parse_header(mgx1_stored, sizeof(mgx1_stored), &h);
    memset(workbuf, 0, sizeof(workbuf));
    rc = mgx_decode(&h, mgx1_stored + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx1_stored) - MGX_HDR_SIZE),
                    workbuf, sizeof(workbuf));
    check_eq("decode(stored) bytes", rc, TEST_RAW1);
    check("decode(stored) content", memcmp(workbuf, expect_raw1, TEST_RAW1) == 0);

    /* Gray 版と線形版は生データが違うが、パレット表を通せば同じ絵になる */
    lin = workbuf + TEST_RAW4;
    mgx_parse_header(mgx4_zlib, sizeof(mgx4_zlib), &h);
    mgx_decode(&h, mgx4_zlib + MGX_HDR_SIZE,
               (u32)(sizeof(mgx4_zlib) - MGX_HDR_SIZE), workbuf, TEST_RAW4);
    mgx_parse_header(mgx4_linear, sizeof(mgx4_linear), &hl);
    mgx_decode(&hl, mgx4_linear + MGX_HDR_SIZE,
               (u32)(sizeof(mgx4_linear) - MGX_HDR_SIZE), lin, TEST_RAW4);
    check("graycode raw differs from linear",
          memcmp(workbuf, lin, TEST_RAW4) != 0);
    same = 1;
    for (y = 0; y < TEST_H && same; y++) {
        for (x = 0; x < TEST_W; x++) {
            int a = h.palette[pixel_index(workbuf, TEST_PITCH, x, y)];
            int b = hl.palette[pixel_index(lin, TEST_PITCH, x, y)];
            if (a != b) { same = 0; break; }
        }
    }
    check("both palettes render the same image", same);

    /* --- bpp=3 / bpp=2: プレーン数と raw_size が bpp に比例する --- */
    mgx_parse_header(mgx3_zlib, sizeof(mgx3_zlib), &h);
    check_eq("bpp3 bpp", h.bpp, 3);
    check_eq("bpp3 npal", h.npal, 8);
    check_eq("bpp3 raw_size", (int)h.raw_size, TEST_PLANE * 3);
    memset(workbuf, 0, sizeof(workbuf));
    rc = mgx_decode(&h, mgx3_zlib + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx3_zlib) - MGX_HDR_SIZE),
                    workbuf, sizeof(workbuf));
    check_eq("decode(bpp3) bytes", rc, TEST_PLANE * 3);
    check("decode(bpp3) content",
          memcmp(workbuf, expect_raw3, TEST_PLANE * 3) == 0);
    {
        static const u8 lv3[8] = { 0,2,4,6,8,10,12,15 };
        int ok3 = 1;
        for (x = 0; x < 8; x++)
            if (h.palette[x ^ (x >> 1)] != lv3[x]) ok3 = 0;
        check("bpp3 palette holds the chosen levels", ok3);
    }

    mgx_parse_header(mgx2_zlib, sizeof(mgx2_zlib), &h);
    check_eq("bpp2 bpp", h.bpp, 2);
    check_eq("bpp2 npal", h.npal, 4);
    check_eq("bpp2 raw_size", (int)h.raw_size, TEST_PLANE * 2);
    memset(workbuf, 0, sizeof(workbuf));
    rc = mgx_decode(&h, mgx2_zlib + MGX_HDR_SIZE,
                    (u32)(sizeof(mgx2_zlib) - MGX_HDR_SIZE),
                    workbuf, sizeof(workbuf));
    check_eq("decode(bpp2) bytes", rc, TEST_PLANE * 2);
    check("decode(bpp2) content",
          memcmp(workbuf, expect_raw2, TEST_PLANE * 2) == 0);
    {
        static const u8 lv2[4] = { 1,7,11,14 };
        int ok2 = 1;
        for (x = 0; x < 4; x++)
            if (h.palette[x ^ (x >> 1)] != lv2[x]) ok2 = 0;
        check("bpp2 palette holds the chosen levels", ok2);
    }
}

