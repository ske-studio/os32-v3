/* 実ファイルがあれば現行 deflate 経路の所要時間も測る (比較の基準) */
static void bench_deflate(const char *path)
{
    u8 hdrbuf[MGX_HDR_SIZE];
    MgxHeader h;
    u8 *payload, *out;
    int fd, rc, n;
    u32 start, end;

    fd = api->sys_open(path, O_RDONLY);
    if (fd < 0) {
        api->kprintf(ATTR_WHITE, "  (%s が無いので deflate 計測は省略)\n", path);
        return;
    }
    n = api->sys_read(fd, hdrbuf, MGX_HDR_SIZE);
    if (n != MGX_HDR_SIZE
        || mgx_parse_header(hdrbuf, MGX_HDR_SIZE, &h) != MGX_OK) {
        api->sys_close(fd);
        api->kprintf(ATTR_WHITE, "  (%s のヘッダが読めない)\n", path);
        return;
    }
    payload = (u8 *)api->mem_alloc(h.data_size);
    out     = (u8 *)api->mem_alloc(h.raw_size);
    if (payload == 0 || out == 0) {
        if (payload) api->mem_free(payload);
        if (out) api->mem_free(out);
        api->sys_close(fd);
        api->kprintf(ATTR_WHITE, "%s", "  (メモリ不足で deflate 計測は省略)\n");
        return;
    }
    api->sys_read(fd, payload, h.data_size);
    api->sys_close(fd);

    /* 出力バッファに一度触れておく (デマンドページングを計測から外す) */
    memset(out, 0, h.raw_size);

    start = api->get_tick();
    rc = mgx_decode(&h, payload, h.data_size, out, h.raw_size);
    end = api->get_tick();

    api->kprintf(ATTR_WHITE,
                 "  bpp=%d: %u B -> %d B (%d プレーン)  %lu ms\n",
                 h.bpp, h.data_size, rc, h.bpp,
                 (unsigned long)(end - start) * 10);
    api->mem_free(payload);
    api->mem_free(out);
}

