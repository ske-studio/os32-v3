void main(int argc, char **argv, KernelAPI *api)
{
    int row, col;
    u32 start_tick, end_tick;
    int char_x = 10, char_y = 10;

    api->kprintf(ATTR_WHITE, "Tilemap Phase 1 Demo\r\n");

    tilemap_init(api);

    /* 画面を黒でクリアして初期化 */
    gfx_clear(0);
    gfx_present();

    /* オフセットを中央寄りに */
    tilemap_set_origin(128, 8);

    /* タイル定義 */
    tilemap_define(1, tile_grass);
    tilemap_define(2, tile_tree);
    tilemap_define(3, tile_char);
    tilemap_define(4, tile_water);

    /* BG0: ベースレイヤー (草) */
    tilemap_fill(0, 1);
    /* 水たまりを少し配置 */
    tilemap_set(0, 5, 5, 4);
    tilemap_set(0, 6, 5, 4);
    tilemap_set(0, 5, 6, 4);

    /* BG1: 木 (透過) */
    tilemap_fill(1, 0); /* 0は空白タイル扱い (透過) にしておく */
    for (row = 2; row < 20; row += 4) {
        for (col = 2; col < 20; col += 4) {
            tilemap_set(1, col, row, 2);
        }
    }
    tilemap_set_visible(1, 1);

    /* BG2: キャラクター */
    tilemap_fill(2, 0);
    tilemap_set(2, char_x, char_y, 3);
    tilemap_set_visible(2, 1);

    /* 初期描画 */
    start_tick = api->get_tick();
    tilemap_compose_btf();
    tilemap_present();
    end_tick = api->get_tick();

    api->kprintf(ATTR_WHITE, "Initial draw: %d ms\r\n", (end_tick - start_tick) * 10);

    /* メインループ */
    while (1) {
        int c = api->kbd_trygetchar();
        if (c == 0x1B) break; /* ESC */

        if (c == 'w' || c == 'a' || c == 's' || c == 'd') {
            /* 古い位置を消す */
            tilemap_set(2, char_x, char_y, 0);

            if (c == 'w' && char_y > 0) char_y--;
            if (c == 's' && char_y < TILEMAP_ROWS - 1) char_y++;
            if (c == 'a' && char_x > 0) char_x--;
            if (c == 'd' && char_x < TILEMAP_COLS - 1) char_x++;

            /* 新しい位置に描画 */
            tilemap_set(2, char_x, char_y, 3);

            start_tick = api->get_tick();
            tilemap_compose_btf();
            tilemap_present();
            end_tick = api->get_tick();
        }
        api->sys_halt();
    }

    tilemap_shutdown();
}
