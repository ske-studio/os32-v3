/* ======================================================================== */
/*  isin — 整数sin (512分割角度, 15bit固定小数点)                           */
/*                                                                          */
/*  引数: angle = 0~511 (0 ~ 360)。範囲外は自動で正規化される。             */
/*  戻り値: -32767 ~ +32767                                                 */
/* ======================================================================== */

i32 isin(int angle)
{
    return (i32)sin_table[angle & 511];
}

/* ======================================================================== */
/*  icos — 整数cos (90 オフセットでsinテーブル参照)                         */
/* ======================================================================== */

i32 icos(int angle)
{
    return (i32)sin_table[(angle + 128) & 511];
}

/* ======================================================================== */
/*  deg_to_idx — 度数(0~359) を LUTインデックス(0~511) に変換               */
/*                                                                          */
/*  deg * 512 / 360 を整数で近似: (deg * 91 + 32) >> 6 = deg * 1.4222       */
/* ======================================================================== */

int deg_to_idx(int deg)
{
    deg = deg % 360;
    if (deg < 0) deg += 360;
    return (deg * 91 + 32) >> 6;
}

/* ======================================================================== */
/*  rad256_to_idx — 256分割角度を512分割LUTインデックスに変換                */
/*                                                                          */
/*  256分割系 (libpyxel等) から512分割系への変換。単純に2倍。                */
/* ======================================================================== */

int rad256_to_idx(int rad256)
{
    return (rad256 * 2) & 511;
}
