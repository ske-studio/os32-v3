/* ======================================================================== */
/*  VEC2.C — 2Dベクトル演算 (libos32math)                                  */
/*                                                                          */
/*  fix16_t ベースの2Dベクトル。ゲームのキャラクター移動、弾幕計算、         */
/*  物理演算などに使用する。                                                 */
/* ======================================================================== */

#include "libos32math.h"

/* ======================================================================== */
/*  vec2_make — ベクトル生成                                                */
/* ======================================================================== */

Vec2 vec2_make(fix16_t x, fix16_t y)
{
    Vec2 v;
    v.x = x;
    v.y = y;
    return v;
}

/* ======================================================================== */
/*  vec2_add — ベクトル加算                                                 */
/* ======================================================================== */

Vec2 vec2_add(Vec2 a, Vec2 b)
{
    Vec2 v;
    v.x = a.x + b.x;
    v.y = a.y + b.y;
    return v;
}

/* ======================================================================== */
/*  vec2_sub — ベクトル減算                                                 */
/* ======================================================================== */

Vec2 vec2_sub(Vec2 a, Vec2 b)
{
    Vec2 v;
    v.x = a.x - b.x;
    v.y = a.y - b.y;
    return v;
}

/* ======================================================================== */
/*  vec2_scale — スカラー倍                                                 */
/* ======================================================================== */

Vec2 vec2_scale(Vec2 v, fix16_t s)
{
    Vec2 r;
    r.x = fix16_mul(v.x, s);
    r.y = fix16_mul(v.y, s);
    return r;
}

/* ======================================================================== */
/*  vec2_dot — 内積                                                         */
/* ======================================================================== */

fix16_t vec2_dot(Vec2 a, Vec2 b)
{
    return fix16_mul(a.x, b.x) + fix16_mul(a.y, b.y);
}

/* ======================================================================== */
/*  vec2_cross — 2D外積 (スカラー値)                                        */
/*                                                                          */
/*  a.x * b.y - a.y * b.x 。符号で左右の判定に使用。                        */
/* ======================================================================== */

fix16_t vec2_cross(Vec2 a, Vec2 b)
{
    return fix16_mul(a.x, b.y) - fix16_mul(a.y, b.x);
}

/* ======================================================================== */
/*  vec2_length_sq — 長さの二乗                                             */
/*                                                                          */
/*  sqrtを呼ばないため、距離比較のみの用途で高速。                           */
/* ======================================================================== */

fix16_t vec2_length_sq(Vec2 v)
{
    return fix16_mul(v.x, v.x) + fix16_mul(v.y, v.y);
}

/* ======================================================================== */
/*  vec2_length — ベクトルの長さ                                            */
/* ======================================================================== */

fix16_t vec2_length(Vec2 v)
{
    return fix16_sqrt(vec2_length_sq(v));
}

/* ======================================================================== */
/*  vec2_normalize — ベクトルの正規化 (長さ1.0にする)                       */
/*                                                                          */
/*  ゼロベクトルの場合はそのまま (0, 0) を返す。                             */
/* ======================================================================== */

Vec2 vec2_normalize(Vec2 v)
{
    Vec2 r;
    fix16_t len = vec2_length(v);
    if (len == 0) {
        r.x = 0;
        r.y = 0;
        return r;
    }
    r.x = fix16_div(v.x, len);
    r.y = fix16_div(v.y, len);
    return r;
}

/* ======================================================================== */
/*  vec2_rotate — ベクトルの回転 (512分割角度)                               */
/*                                                                          */
/*  回転行列:                                                               */
/*    x' = x*cos - y*sin                                                    */
/*    y' = x*sin + y*cos                                                    */
/*                                                                          */
/*  isin/icos の値域は -32767~+32767 なので、                                */
/*  結果を ISIN_SCALE で割って正規化する。                                   */
/* ======================================================================== */

Vec2 vec2_rotate(Vec2 v, int angle)
{
    Vec2 r;
    i32 c = icos(angle);
    i32 s = isin(angle);

    /*
     * fix16_mul は Q16.16 同士の乗算。
     * isin/icos は Q0.15 (実質 i32) なので、まず Q16.16 に変換してから乗算し、
     * その後 ISIN_SCALE で割って正規化する。
     *
     * 手順:
     *   temp = v.x * c  (ここで c は -32767~+32767 の整数)
     *   temp は Q16.16 * 整数 = Q16.16 スケールされた値
     *   最終結果 = temp / ISIN_SCALE
     */
    r.x = (fix16_t)(((long long)v.x * c - (long long)v.y * s) / ISIN_SCALE);
    r.y = (fix16_t)(((long long)v.x * s + (long long)v.y * c) / ISIN_SCALE);

    return r;
}

/* ======================================================================== */
/*  vec2_distance — 2点間距離                                               */
/* ======================================================================== */

fix16_t vec2_distance(Vec2 a, Vec2 b)
{
    Vec2 d = vec2_sub(b, a);
    return vec2_length(d);
}

/* ======================================================================== */
/*  vec2_lerp — ベクトル線形補間                                            */
/*                                                                          */
/*  t = 0.0 で a, t = 1.0 で b を返す。                                     */
/* ======================================================================== */

Vec2 vec2_lerp(Vec2 a, Vec2 b, fix16_t t)
{
    Vec2 r;
    r.x = a.x + fix16_mul(b.x - a.x, t);
    r.y = a.y + fix16_mul(b.y - a.y, t);
    return r;
}
