/* ======================================================================== */
/*  ATAN2.C — 整数 atan2 (CORDIC方式) (libos32math)                        */
/*                                                                          */
/*  CORDICアルゴリズムで y, x から角度を計算。                               */
/*  戻り値は 0~511 (512分割角度, isin/icos と互換)。                        */
/* ======================================================================== */

#include "libos32math.h"

/*
 * CORDIC の atan テーブル (512分割角度系)
 * atan(2^-i) を 512分割角度で表現 (i = 0..14)
 *
 * atan(1)     = 45deg = 64.0  (512/360*45)
 * atan(0.5)   = 26.565deg = 37.8...
 * ...
 */
static const i16 cordic_atan[15] = {
    64,   /* atan(2^0)  = 45.000 deg */
    38,   /* atan(2^-1) = 26.565 deg */
    20,   /* atan(2^-2) = 14.036 deg */
    10,   /* atan(2^-3) = 7.125 deg  */
     5,   /* atan(2^-4) = 3.576 deg  */
     3,   /* atan(2^-5) = 1.790 deg  */
     1,   /* atan(2^-6) = 0.895 deg  */
     1,   /* atan(2^-7) = 0.448 deg  */
     0,   /* atan(2^-8)  以下は0に丸め */
     0,
     0,
     0,
     0,
     0,
     0
};

/* ======================================================================== */
/*  iatan2 — 整数 atan2 (CORDIC 方式)                                       */
/*                                                                          */
/*  引数: y, x (符号付き整数)                                               */
/*  戻り値: 0 ~ 511 (512分割角度)                                           */
/*          0=右(+X), 128=下(+Y), 256=左(-X), 384=上(-Y)                    */
/*                                                                          */
/*  x=0, y=0 のときは 0 を返す。                                            */
/* ======================================================================== */

int iatan2(i32 y, i32 x)
{
    i32 cx, cy, nx;
    int angle;
    int i;

    if (x == 0 && y == 0) return 0;

    /* 第1象限に写像してCORDIC実行、後で補正 */
    cx = (x < 0) ? -x : x;
    cy = (y < 0) ? -y : y;
    angle = 0;

    /* CORDIC ベクトルモード: ベクトル(cx, cy)をX軸に回転 */
    for (i = 0; i < 8; i++) {
        if (cy > 0) {
            /* 時計回りに回転 */
            nx = cx + (cy >> i);
            cy = cy - (cx >> i);
            cx = nx;
            angle += cordic_atan[i];
        } else {
            /* 反時計回りに回転 */
            nx = cx - (cy >> i);
            cy = cy + (cx >> i);
            cx = nx;
            angle -= cordic_atan[i];
        }
    }

    /* 角度を正に正規化 (ここまでで第1象限の角度が得られる) */
    if (angle < 0) angle = -angle;

    /* 象限の補正 */
    if (x < 0 && y >= 0) {
        /* 第2象限: 180 - angle */
        angle = 256 - angle;
    } else if (x < 0 && y < 0) {
        /* 第3象限: 180 + angle */
        angle = 256 + angle;
    } else if (x >= 0 && y < 0) {
        /* 第4象限: 360 - angle */
        angle = 512 - angle;
    }
    /* x >= 0, y >= 0: 第1象限はそのまま */

    return angle & 511;
}

/* ======================================================================== */
/*  angle_between — 2点間の角度 (512分割角度)                                */
/*                                                                          */
/*  (x0, y0) から (x1, y1) への方向角を返す。                               */
/* ======================================================================== */

int angle_between(int x0, int y0, int x1, int y1)
{
    return iatan2((i32)(y1 - y0), (i32)(x1 - x0));
}
