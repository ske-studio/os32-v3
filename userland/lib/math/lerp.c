/* ======================================================================== */
/*  LERP.C — 線形補間・イージング関数群 (libos32math)                      */
/*                                                                          */
/*  UIアニメーション、ゲームオブジェクトの滑らかな移動に使用する。            */
/*  すべての関数は Q16.16 固定小数点で動作する。                              */
/*                                                                          */
/*  イージング関数の入力 t は 0.0 (=0) ~ 1.0 (=65536) の範囲。              */
/*  出力も同じ範囲 (一部 ease_bounce は overshoot あり)。                     */
/* ======================================================================== */

#include "libos32math.h"

/* ======================================================================== */
/*  fix16_lerp — 線形補間                                                   */
/*                                                                          */
/*  a + (b - a) * t  (t は Q16.16, 0.0~1.0)                                */
/* ======================================================================== */

fix16_t fix16_lerp(fix16_t a, fix16_t b, fix16_t t)
{
    return a + fix16_mul(b - a, t);
}

/* ======================================================================== */
/*  lerp_int — 整数線形補間                                                 */
/*                                                                          */
/*  a + (b - a) * t / t_max  (固定小数点を使わない整数版)                    */
/*  フレーム番号 / 全フレーム数 のような用途向け。                           */
/* ======================================================================== */

int lerp_int(int a, int b, int t, int t_max)
{
    if (t_max <= 0) return a;
    if (t <= 0) return a;
    if (t >= t_max) return b;
    return a + (int)(((long)(b - a) * t) / t_max);
}

/* ======================================================================== */
/*  ease_in_quad — 2次加速イージング                                        */
/*                                                                          */
/*  f(t) = t^2                                                              */
/* ======================================================================== */

fix16_t ease_in_quad(fix16_t t)
{
    return fix16_mul(t, t);
}

/* ======================================================================== */
/*  ease_out_quad — 2次減速イージング                                       */
/*                                                                          */
/*  f(t) = 1 - (1-t)^2 = 2t - t^2                                          */
/* ======================================================================== */

fix16_t ease_out_quad(fix16_t t)
{
    fix16_t inv = FIX16_ONE - t;
    return FIX16_ONE - fix16_mul(inv, inv);
}

/* ======================================================================== */
/*  ease_in_out_quad — 2次S字イージング                                     */
/*                                                                          */
/*  t < 0.5: 2*t^2                                                         */
/*  t >= 0.5: 1 - (-2t+2)^2 / 2                                            */
/* ======================================================================== */

fix16_t ease_in_out_quad(fix16_t t)
{
    if (t < FIX16_HALF) {
        /* 2 * t * t  (t は 0~0.5 なので 2t は 0~1) */
        return fix16_mul(t, t) << 1;
    } else {
        fix16_t inv = FIX16_ONE - t;
        return FIX16_ONE - (fix16_mul(inv, inv) << 1);
    }
}

/* ======================================================================== */
/*  ease_in_cubic — 3次加速イージング                                       */
/*                                                                          */
/*  f(t) = t^3                                                              */
/* ======================================================================== */

fix16_t ease_in_cubic(fix16_t t)
{
    return fix16_mul(fix16_mul(t, t), t);
}

/* ======================================================================== */
/*  ease_out_cubic — 3次減速イージング                                      */
/*                                                                          */
/*  f(t) = 1 - (1-t)^3                                                     */
/* ======================================================================== */

fix16_t ease_out_cubic(fix16_t t)
{
    fix16_t inv = FIX16_ONE - t;
    return FIX16_ONE - fix16_mul(fix16_mul(inv, inv), inv);
}

/* ======================================================================== */
/*  ease_in_out_cubic — 3次S字イージング                                    */
/*                                                                          */
/*  t < 0.5: 4*t^3                                                         */
/*  t >= 0.5: 1 - (-2t+2)^3 / 2                                            */
/* ======================================================================== */

fix16_t ease_in_out_cubic(fix16_t t)
{
    if (t < FIX16_HALF) {
        /* 4 * t^3 = (2t)^2 * t * ... ただし overflow に注意 */
        fix16_t t2 = fix16_mul(t, t);
        return fix16_mul(t2, t) << 2;
    } else {
        fix16_t inv = FIX16_ONE - t;
        fix16_t inv2 = fix16_mul(inv, inv);
        return FIX16_ONE - (fix16_mul(inv2, inv) << 2);
    }
}

/* ======================================================================== */
/*  ease_bounce — バウンスイージング (ease-out bounce)                      */
/*                                                                          */
/*  床に落ちたボールが跳ね返るような動き。                                   */
/*  整数演算で近似的に実装。                                                 */
/* ======================================================================== */

fix16_t ease_bounce(fix16_t t)
{
    /*
     * 標準バウンス関数の Q16.16 近似:
     *
     * 区間1: t < 4/11  (= 23831)  -> 121/16 * t^2
     * 区間2: t < 8/11  (= 47663)  -> 121/16 * (t - 6/11)^2 + 3/4
     * 区間3: t < 10/11 (= 59578)  -> 121/16 * (t - 9/11)^2 + 15/16
     * 区間4: t >= 10/11           -> 121/16 * (t - 21/22)^2 + 63/64
     *
     * 121/16 = 7.5625 -> Q16.16: 495616
     */
    fix16_t n1 = 495616;  /* 7.5625 * 65536 */
    fix16_t d;

    if (t < 23831) {
        /* 区間1: n1 * t * t */
        return fix16_mul(n1, fix16_mul(t, t));
    } else if (t < 47663) {
        /* 区間2: t -= 6/11 (= 35747) */
        d = t - 35747;
        return fix16_mul(n1, fix16_mul(d, d)) + 49152;  /* + 0.75 */
    } else if (t < 59578) {
        /* 区間3: t -= 9/11 (= 53620) */
        d = t - 53620;
        return fix16_mul(n1, fix16_mul(d, d)) + 61440;  /* + 15/16 */
    } else {
        /* 区間4: t -= 21/22 (= 62532) */
        d = t - 62532;
        return fix16_mul(n1, fix16_mul(d, d)) + 64512;  /* + 63/64 */
    }
}
