/* ======================================================================== */
/*  FIX16.C — Q16.16 固定小数点四則演算 (libos32math)                       */
/*                                                                          */
/*  32bit 整数の上位16bitを整数部、下位16bitを小数部として扱う。             */
/*  乗算は64bit中間値を使用し、オーバーフローを防ぐ。                        */
/* ======================================================================== */

#include "libos32math.h"

/* ======================================================================== */
/*  fix16_mul — Q16.16 乗算                                                 */
/*                                                                          */
/*  (a * b) >> 16 を64bit演算で計算。オーバーフロー防止。                    */
/* ======================================================================== */

fix16_t fix16_mul(fix16_t a, fix16_t b)
{
    long long result = (long long)a * (long long)b;
    return (fix16_t)(result >> 16);
}

/* ======================================================================== */
/*  fix16_div — Q16.16 除算                                                 */
/*                                                                          */
/*  (a << 16) / b を64bit演算で計算。ゼロ除算はそのまま (呼び出し側が保証)。 */
/* ======================================================================== */

fix16_t fix16_div(fix16_t a, fix16_t b)
{
    long long result;
    if (b == 0) return 0;
    result = ((long long)a << 16) / (long long)b;
    return (fix16_t)result;
}

/* ======================================================================== */
/*  fix16_from_frac — 分数を Q16.16 に変換                                  */
/*                                                                          */
/*  num/den を固定小数点で表現。                                            */
/* ======================================================================== */

fix16_t fix16_from_frac(int num, int den)
{
    if (den == 0) return 0;
    return (fix16_t)(((long long)num << 16) / den);
}

/* ======================================================================== */
/*  fix16_abs — 絶対値                                                      */
/* ======================================================================== */

fix16_t fix16_abs(fix16_t x)
{
    return (x < 0) ? -x : x;
}

/* ======================================================================== */
/*  fix16_ceil — 切り上げ (整数部分に繰り上げ)                              */
/* ======================================================================== */

fix16_t fix16_ceil(fix16_t x)
{
    if (x & 0xFFFF) {
        return (x & 0xFFFF0000) + FIX16_ONE;
    }
    return x;
}

/* ======================================================================== */
/*  fix16_floor — 切り捨て (整数部分のみ残す)                               */
/* ======================================================================== */

fix16_t fix16_floor(fix16_t x)
{
    return x & 0xFFFF0000;
}

/* ======================================================================== */
/*  fix16_round — 四捨五入                                                  */
/* ======================================================================== */

fix16_t fix16_round(fix16_t x)
{
    return (x + FIX16_HALF) & 0xFFFF0000;
}

/* ======================================================================== */
/*  fix16_min / fix16_max / fix16_clamp                                     */
/* ======================================================================== */

fix16_t fix16_min(fix16_t a, fix16_t b)
{
    return (a < b) ? a : b;
}

fix16_t fix16_max(fix16_t a, fix16_t b)
{
    return (a > b) ? a : b;
}

fix16_t fix16_clamp(fix16_t x, fix16_t lo, fix16_t hi)
{
    if (x < lo) return lo;
    if (x > hi) return hi;
    return x;
}
