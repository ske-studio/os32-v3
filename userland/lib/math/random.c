/* ======================================================================== */
/*  RANDOM.C — xorshift32 擬似乱数生成器 (libos32math)                     */
/*                                                                          */
/*  周期 2^32-1。ゲーム用途に十分な品質と速度を持つ。                        */
/*  シフト+XOR のみで構成 (乗除算なし)。                                    */
/* ======================================================================== */

#include "libos32math.h"

/* 乱数状態 (ゼロは使用不可、デフォルトシードで初期化) */
static u32 rng_state = 2463534242UL;

/* ======================================================================== */
/*  rng_seed — シード設定                                                   */
/*                                                                          */
/*  seed が 0 の場合はデフォルト値を使用 (xorshift はゼロ状態から復帰不能)。 */
/* ======================================================================== */

void rng_seed(u32 seed)
{
    rng_state = (seed != 0) ? seed : 2463534242UL;
}

/* ======================================================================== */
/*  rng_next — 次の乱数値を生成 (xorshift32)                                */
/*                                                                          */
/*  Marsaglia (2003) の xorshift パラメータ: 13, 17, 5                      */
/* ======================================================================== */

u32 rng_next(void)
{
    u32 x = rng_state;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    rng_state = x;
    return x;
}

/* ======================================================================== */
/*  rng_range — 範囲指定乱数 [min, max]                                     */
/*                                                                          */
/*  min == max の場合は min を返す。                                         */
/*  剰余によるバイアスは無視 (ゲーム用途では問題にならない)。                */
/* ======================================================================== */

int rng_range(int min, int max)
{
    u32 range;
    if (min >= max) return min;
    range = (u32)(max - min + 1);
    return min + (int)(rng_next() % range);
}

/* ======================================================================== */
/*  rng_fix16 — 0.0~1.0 の Q16.16 乱数                                     */
/*                                                                          */
/*  上位16bitを捨てて下位16bitを小数部として使用。                           */
/*  戻り値: 0 ~ 65535 (0.0 ~ 0.999985)                                     */
/* ======================================================================== */

fix16_t rng_fix16(void)
{
    return (fix16_t)(rng_next() & 0xFFFF);
}
