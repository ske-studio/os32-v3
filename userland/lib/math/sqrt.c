/* ======================================================================== */
/*  SQRT.C — 整数平方根・距離計算 (libos32math)                            */
/*                                                                          */
/*  isqrt: ニュートン法 (Heron法) による整数平方根。                        */
/*  fix16_sqrt: Q16.16 対応の平方根。                                       */
/*  fast_distance: α-max-plus-β-min 近似による高速距離計算。               */
/* ======================================================================== */

#include "libos32math.h"

/* ======================================================================== */
/*  isqrt — 整数平方根 (ニュートン法)                                       */
/*                                                                          */
/*  floor(sqrt(n)) を返す。n=0 のときは 0。                                 */
/*  最大6回の反復で u32 全範囲に対応。                                       */
/* ======================================================================== */

u32 isqrt(u32 n)
{
    u32 x, x1;

    if (n == 0) return 0;
    if (n < 4) return 1;

    /* 初期推定値: n のビット長の半分からスタート */
    x = n;
    x1 = (x + 1) >> 1;

    /* ニュートン法の反復 */
    while (x1 < x) {
        x = x1;
        x1 = (x + n / x) >> 1;
    }
    return x;
}

/* ======================================================================== */
/*  fix16_sqrt — Q16.16 平方根                                              */
/*                                                                          */
/*  入力値を32bit左シフトしてからisqrtを呼び、Q16.16の精度を得る。          */
/*  大きな値ではオーバーフローを避けるため工夫が必要。                       */
/* ======================================================================== */

fix16_t fix16_sqrt(fix16_t x)
{
    u32 val;
    u32 result;

    if (x <= 0) return 0;

    val = (u32)x;

    /*
     * sqrt(x_fix16) = sqrt(x_real * 65536) = sqrt(x_real) * 256
     * Q16.16 で結果を得るには、さらに256倍が必要:
     *   sqrt(x_fix16) * 256 = sqrt(x_fix16 * 65536)
     *
     * ただし x_fix16 * 65536 は u32 の範囲を超える可能性があるため、
     * 2段階で計算する:
     *   result = isqrt(val) << 8  (粗い近似)
     *   微調整で精度を上げる
     */
    result = isqrt(val);
    /* Q16.16 に変換 (256倍) */
    result <<= 8;

    /* ニュートン法で1段階精度を上げる */
    if (result > 0) {
        fix16_t check = fix16_mul((fix16_t)result, (fix16_t)result);
        if (check < x) {
            result += (u32)fix16_div(x - check, (fix16_t)(result << 1));
        }
    }

    return (fix16_t)result;
}

/* ======================================================================== */
/*  fast_distance_sq — 距離の二乗 (sqrtなし)                                */
/*                                                                          */
/*  衝突判定等の距離比較で使用。sqrtを呼ばないため高速。                     */
/* ======================================================================== */

u32 fast_distance_sq(int dx, int dy)
{
    return (u32)((long)dx * dx + (long)dy * dy);
}

/* ======================================================================== */
/*  fast_distance — 高速距離近似 (alpha-max-plus-beta-min)                  */
/*                                                                          */
/*  alpha=1, beta=3/8 の近似。最大誤差 ~3.5%。                              */
/*  正確な距離が不要なケース (音量減衰、大まかな距離ソート等) に適する。      */
/* ======================================================================== */

u32 fast_distance(int dx, int dy)
{
    u32 a, b;

    /* 絶対値を取る */
    a = (dx < 0) ? (u32)(-dx) : (u32)dx;
    b = (dy < 0) ? (u32)(-dy) : (u32)dy;

    /* a >= b を保証 */
    if (a < b) {
        u32 tmp = a;
        a = b;
        b = tmp;
    }

    /* alpha*max + beta*min = max + 3/8*min = max + (3*min)/8 */
    return a + ((3 * b) >> 3);
}
