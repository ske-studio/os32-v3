/* ====================================================================== */
/*  fast_div — 逆数LUTによる高速除算                                        */
/*                                                                          */
/*  a / b を fix16_mul(a, recip_table[b]) で計算。                          */
/*  b が 1~256 の範囲外の場合は通常除算にフォールバック。                    */
/* ====================================================================== */

pub fn fast_div(a: Fix16, b: i32) -> Fix16 {
    if b <= 0 || b > 256 {
        return a / Fix16::from_int(b);
    }
    a * Fix16::from_raw(RECIP_TABLE[b as usize])
}

/* ====================================================================== */
/*  C互換FFI関数                                                            */
/* ====================================================================== */

#[no_mangle]
pub extern "C" fn rs_fast_div(a: i32, b: i32) -> i32 {
    fast_div(Fix16::from_raw(a), b).raw()
}

/* ====================================================================== */
/*  テスト                                                                  */
/* ====================================================================== */

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_fast_div_basic() {
        let a = Fix16::from_int(10);
        let result = fast_div(a, 2);
        assert_eq!(result.to_int(), 5);
    }

    #[test]
    fn test_fast_div_boundary() {
        let a = Fix16::from_int(256);
        let result = fast_div(a, 256);
        assert_eq!(result.to_int(), 1);
    }

    #[test]
    fn test_fast_div_fallback() {
        /* b > 256 → 通常除算にフォールバック */
        let a = Fix16::from_int(1000);
        let result = fast_div(a, 500);
        assert_eq!(result.to_int(), 2);
    }
}
