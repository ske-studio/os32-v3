#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_isin_basic() {
        assert_eq!(isin(0), 0);       /* sin(0°) = 0 */
        assert_eq!(isin(128), 32767); /* sin(90°) = 1.0 */
        assert_eq!(isin(256), 0);     /* sin(180°) = 0 */
        assert_eq!(isin(384), -32767);/* sin(270°) = -1.0 */
    }

    #[test]
    fn test_icos_basic() {
        assert_eq!(icos(0), 32767);   /* cos(0°) = 1.0 */
        assert_eq!(icos(128), 0);     /* cos(90°) = 0 */
        assert_eq!(icos(256), -32767);/* cos(180°) = -1.0 */
    }

    #[test]
    fn test_angle_wraparound() {
        assert_eq!(isin(512), isin(0));   /* 360° = 0° */
        assert_eq!(isin(-128), isin(384));/* -90° = 270° */
    }

    #[test]
    fn test_deg_to_idx() {
        assert_eq!(deg_to_idx(0), 0);
        assert_eq!(deg_to_idx(90), 128);
        assert_eq!(deg_to_idx(180), 256);
        assert_eq!(deg_to_idx(360), 0); /* 360° -> 0 */
    }
}
