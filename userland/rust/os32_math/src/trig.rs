/* ====================================================================== */
/*  isin — 整数sin (512分割角度, 15bit固定小数点)                           */
/*                                                                          */
/*  引数: angle = 0~511 (0° ~ 360°)。範囲外は自動で正規化される。          */
/*  戻り値: -32767 ~ +32767                                                 */
/* ====================================================================== */

#[inline]
pub fn isin(angle: i32) -> i32 {
    SIN_TABLE[(angle & 511) as usize] as i32
}

/* ====================================================================== */
/*  icos — 整数cos (90°オフセットでsinテーブル参照)                         */
/* ====================================================================== */

#[inline]
pub fn icos(angle: i32) -> i32 {
    SIN_TABLE[((angle + 128) & 511) as usize] as i32
}

/* ====================================================================== */
/*  deg_to_idx — 度数(0~359) を LUTインデックス(0~511) に変換               */
/*                                                                          */
/*  deg * 512 / 360 を整数で近似: (deg * 91 + 32) >> 6                     */
/* ====================================================================== */

pub fn deg_to_idx(deg: i32) -> i32 {
    let mut d = deg % 360;
    if d < 0 { d += 360; }
    (d * 91 + 32) >> 6
}

/* ====================================================================== */
/*  rad256_to_idx — 256分割角度を512分割LUTインデックスに変換                */
/* ====================================================================== */

#[inline]
pub fn rad256_to_idx(rad256: i32) -> i32 {
    (rad256 * 2) & 511
}

/* ====================================================================== */
/*  C互換FFI関数                                                            */
/* ====================================================================== */

#[no_mangle]
pub extern "C" fn rs_isin(angle: i32) -> i32 { isin(angle) }

#[no_mangle]
pub extern "C" fn rs_icos(angle: i32) -> i32 { icos(angle) }

#[no_mangle]
pub extern "C" fn rs_deg_to_idx(deg: i32) -> i32 { deg_to_idx(deg) }

#[no_mangle]
pub extern "C" fn rs_rad256_to_idx(rad256: i32) -> i32 { rad256_to_idx(rad256) }

