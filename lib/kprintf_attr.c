/* ======================================================================== */
/*  KPRINTF_ATTR.C — kprintf の属性を PC-98 のテキスト属性へ直す            */
/*                                                                          */
/*  ここには副作用のある行を 1 つも置かない (I/O も VRAM も触らない)。      */
/*  lib/kprintf.c から切り出してあるのは、実機でしか見えない変換を          */
/*  ホストで試験するため。                                                  */
/*    試験: tools/tests/test_kprintf_attr.py                                */
/*    記録: tools/tests/kprintf_attr_tdd.md                                 */
/*                                                                          */
/*  なぜ要るか (2026-09-22、実機 PC-9821Ra266):                             */
/*    カーネルの kprintf 呼び出しは 73 か所が `kprintf(0x07, …)` で、       */
/*    これは PC/AT (CGA) 流の「明るい灰色の文字」のつもりで書かれていた。   */
/*    PC-98 のテキスト属性はビットの意味がまったく違う                      */
/*    (include/pc98.h の TATTR_*: bit0 = 表示、bit5/6/7 = 青/赤/緑、        */
/*     bit1 = ブリンク、bit2 = リバース) ので、07h はそのまま書くと         */
/*    「色ビット無し (= 黒) + リバース + ブリンク + 表示」になり、          */
/*    **画面に 1 文字も読めない**。0Ah / 0Ch / 0Eh / 02h / 04h / 0Bh は     */
/*    bit0 (表示) すら立っておらず完全に不可視だった。                      */
/*    エミュレータの /api/tvram は文字コードだけを返すので、属性が          */
/*    壊れていても「出ている」ように見えて誰も気づかなかった。              */
/*                                                                          */
/*  出典: PC9800Bible §3-2 (テキスト属性) / docs/POLICY_DEBUG.md §4         */
/* ======================================================================== */

#include "types.h"
#include "pc98.h"
#include "kprintf.h"

/* ======================================================================== */
/*  PC-98 の色ビット (GRB)。ここが 1 つでも立っていれば、呼び出し側は        */
/*  最初から PC-98 の属性を書いている (TATTR_WHITE = E1h など) と判断する。  */
/*  PC/AT 流の値は下位 4 ビットにしか色を持たないので、両者は衝突しない。    */
/* ======================================================================== */
#define KPRINTF_PC98_COLOR_MASK   (TATTR_B_GREEN | TATTR_B_RED | TATTR_B_BLUE)

/* ======================================================================== */
/*  PC/AT (CGA/VGA) のアトリビュートバイトの前景色 (下位 4 ビット)。         */
/*    bit0 = 青 / bit1 = 緑 / bit2 = 赤 / bit3 = 輝度                       */
/*  PC-98 のテキスト属性に輝度は無いので bit3 は捨てる。                    */
/* ======================================================================== */
#define KPRINTF_CGA_FG_BLUE       0x01
#define KPRINTF_CGA_FG_GREEN      0x02
#define KPRINTF_CGA_FG_RED        0x04

/* ======================================================================== */
/*  kprintf_attr_to_pc98 — 属性 1 バイトを PC-98 の属性へ直す (純粋関数)    */
/*                                                                          */
/*  規則は 3 つだけ:                                                        */
/*    1. PC-98 の色ビット (E0h) が立っていれば **そのまま通す**。            */
/*       0xC1 (黄) / 0xE1 (白) / 0xA1 (水) のような正しい呼び出しを         */
/*       壊さないため。ただし bit0 (表示) が落ちていれば立てる              */
/*       — 色を指定したのに見えない、は意図ではあり得ない。                 */
/*    2. それ以外は PC/AT の前景色として読み替える。輝度 (bit3) は捨てる。   */
/*    3. 色が黒 (= 0) になったら白にする。PC-98 の黒は「シークレット」で    */
/*       何も見えないので、既定色を持たない呼び出し (kprintf(0, …)) を      */
/*       黙って消さない。                                                   */
/*                                                                          */
/*  リバース (bit2) とブリンク (bit1) は **付けない**。PC/AT 流の値の       */
/*  下位ビットは前景色であって、反転や点滅の指定ではない。                  */
/* ======================================================================== */
u8 kprintf_attr_to_pc98(u8 attr)
{
    u8 color;

    if ((attr & KPRINTF_PC98_COLOR_MASK) != 0) {
        return (u8)(attr | TATTR_VISIBLE);
    }

    color = 0;
    if ((attr & KPRINTF_CGA_FG_BLUE) != 0)  color |= TATTR_B_BLUE;
    if ((attr & KPRINTF_CGA_FG_GREEN) != 0) color |= TATTR_B_GREEN;
    if ((attr & KPRINTF_CGA_FG_RED) != 0)   color |= TATTR_B_RED;

    if (color == 0) {
        color = (u8)(TATTR_WHITE & KPRINTF_PC98_COLOR_MASK);
    }

    return (u8)(color | TATTR_VISIBLE);
}
