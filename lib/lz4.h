#ifndef LZ4_H
#define LZ4_H

/* ======================================================================== */
/*  LZ4.H -- LZ4 ブロック形式 展開ルーチン (OS32カーネル用)                  */
/*                                                                          */
/*  LZ4ブロック仕様 (lz4_Block_format.md) に準拠した Safe デコーダ。         */
/*  公式 LZ4 バイナリ / Python lz4.block で圧縮したデータを展開可能。        */
/*  カーネルにはデコーダのみ配置。エンコーダは外部プログラムに配置。          */
/* ======================================================================== */

#include "types.h"

/*
 * LZ4ブロック展開 (Safe版)
 *
 * src:             LZ4ブロック形式の圧縮データ
 * compressed_size: 圧縮データのサイズ (バイト)
 * dst:             展開先バッファ (事前確保済み)
 * dst_capacity:    展開先バッファの最大サイズ (バイト)
 *
 * 戻り値: 展開後のバイト数 (>= 0)
 *         エラー時: 負数
 *           -1: 入力データ不正 (破損)
 *           -2: 出力バッファ不足
 *
 * 備考:
 *   - スタックのみ使用 (ヒープ/BSS不使用、辞書バッファ不要)
 *   - スタック消費: ~16バイト (ローカル変数のみ)
 *   - 不正入力に対して安全 (バッファオーバーフロー防止)
 */
int lz4_decode(const u8 *src, int compressed_size,
               u8 *dst, int dst_capacity);

#endif /* LZ4_H */
